#!/usr/bin/env python
"""Write ashlar/INDEX.md: one table per act and kind, one row per asset ID, 2D and 3D side by side.

The two stage trees mirror each other:   ashlar/art/<act>/<kind>/<ID>/   <->   ashlar/3d/<act>/<kind>/<ID>/
Heroes and NPCs are not act-bound:        ashlar/art/heroes/<ID>/vA ...  <->   ashlar/3d/heroes/<ID>/vA ...

Columns: concept folder, newest concept image (by mtime, from the asset's own folders, never from `_work/`, `_*`, views/,
rig/, textures/), 3D folder, GLB files (the asset's own, then its weapons/). "—" = nothing on that side.

Usage:  python ashlar/pipeline/index/build_index.py [--root ashlar] [--out ashlar/INDEX.md] [--stdout]
Only the standard library is used. Run it after a layout change or a new asset; the file is generated, do not edit it.
"""
import argparse
import os
import posixpath
import sys
from collections import defaultdict
from urllib.parse import quote

IMG = ('.png', '.jpg', '.jpeg', '.webp')
SKIP_DIRS = {'views', 'rig', 'textures', 'logs', 'prompts', 'templates', 'rows', 'hud', 'prologue'}
ACT_PREFIX = 'act-'
NON_ACT = ('heroes', 'npcs', 'common')
KIND_TITLES = {'monsters': 'Monsters', 'environments': 'Environments (asset groups)', 'heroes': 'Heroes', 'npcs': 'NPCs',
               'common': 'Common 3D props (not act-bound)'}


def skip_dir(name):
    return name.startswith('_') or name.startswith('rig') or name in SKIP_DIRS


def collect(root):
    """-> [(path relative to root with '/', mtime)] for art/ and 3d/ (files only)"""
    out = []
    for tree in ('art', '3d'):
        base = os.path.join(root, tree)
        for dp, dns, fns in os.walk(base):
            rel = os.path.relpath(dp, root).replace('\\', '/')
            dns[:] = [d for d in dns if d not in ('__pycache__', 'node_modules')]
            for f in fns:
                p = os.path.join(dp, f)
                try:
                    out.append((rel + '/' + f, os.path.getmtime(p)))
                except OSError:
                    pass
    return out


def _slot(parts):
    """('art'|'3d', section, kind, id, rest) of a file path, or None when it is not under an asset folder"""
    if len(parts) < 4:
        return None
    tree, a = parts[0], parts[1]
    if tree not in ('art', '3d'):
        return None
    if a.startswith(ACT_PREFIX):
        if len(parts) < 5 or parts[2].startswith('_'):
            return None
        return tree, a, parts[2], parts[3], parts[4:]
    if a in NON_ACT:
        if a == 'common':
            return (tree, a, 'common', parts[2], parts[3:]) if len(parts) >= 4 else None
        return tree, a, a, parts[2], parts[3:]
    return None


def build_model(files):
    """-> {(section, kind): {id: {'art': {...}, '3d': {...}}}}"""
    model = defaultdict(lambda: defaultdict(lambda: {'art': None, '3d': None}))
    for rel, mtime in files:
        parts = rel.split('/')
        s = _slot(parts)
        if not s:
            continue
        tree, section, kind, aid, rest = s
        if aid.startswith('_') or aid in ('index.html', 'manifest.json'):
            continue
        ent = model[(section, kind)][aid]
        side = ent[tree]
        if side is None:
            side = ent[tree] = {'dir': '/'.join(parts[:parts.index(aid) + 1]), 'img': None, 'glb': []}
        name = rest[-1]
        low = name.lower()
        dirs = rest[:-1]
        if any(skip_dir(d) for d in dirs if d != 'weapons') or any(d == '_work' for d in dirs):
            continue
        if tree == 'art' and low.endswith(IMG) and 'reject' not in low:  # P03 keeps concept_r2c_rejected.png beside the finals
            if side['img'] is None or mtime > side['img'][1]:
                side['img'] = (rel, mtime)
        elif tree == '3d' and low.endswith('.glb'):
            side['glb'].append(rel)
    return model


def link(label, target, from_dir, folder=False):
    rel = posixpath.relpath(target, from_dir)
    return '[%s](%s%s)' % (label, quote(rel), '/' if folder else '')


def fmt_glb(paths, from_dir):
    if not paths:
        return '—'
    return '<br>'.join(link(posixpath.basename(p), p, from_dir) for p in sorted(paths, key=lambda p: (p.count('/'), p)))


def render(files, title='ASHLAR asset index'):
    model = build_model(files)
    here = ''  # INDEX.md sits in ashlar/: every target is relative to it
    L = ['# ' + title, '',
         'Generated by `ashlar/pipeline/index/build_index.py`. Do not edit; run the script again after a layout change.', '',
         'One row per asset ID. `art/` and `3d/` use the same path for the same asset: '
         '`<act>/<kind>/<ID>/` (heroes and NPCs: `heroes/<ID>/`, `npcs/<ID>/`). "—" = nothing on that side yet.', '']
    other = {'heroes': 1, 'npcs': 2, 'common': 3}
    order = sorted(model, key=lambda k: (0 if k[0].startswith(ACT_PREFIX) else other.get(k[0], 9), k[0], 0 if k[1] == 'monsters' else 1, k[1]))
    for section, kind in order:
        rows = model[(section, kind)]
        head = ('%s: %s' % (section.replace('act-', 'Act '), KIND_TITLES.get(kind, kind))
                if section.startswith(ACT_PREFIX) else KIND_TITLES.get(kind, kind))
        L += ['## ' + head, '', '| ID | Concept folder | Newest concept | 3D folder | GLB |', '| --- | --- | --- | --- | --- |']
        for aid in sorted(rows):
            e = rows[aid]
            a, d = e['art'], e['3d']
            c_dir = link(aid, a['dir'], here, True) if a else '—'
            c_img = link(posixpath.relpath(a['img'][0], a['dir']), a['img'][0], here) if a and a['img'] else '—'  # label = vA/concept_r2.png
            d_dir = link(aid, d['dir'], here, True) if d else '—'
            d_glb = fmt_glb(d['glb'], here) if d else '—'
            L.append('| %s | %s | %s | %s | %s |' % (aid, c_dir, c_img, d_dir, d_glb))
        L.append('')
    return '\n'.join(L).rstrip('\n') + '\n'


def main(argv=None):
    here = os.path.dirname(os.path.abspath(__file__))
    default_root = os.path.abspath(os.path.join(here, '..', '..'))
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--root', default=default_root, help='the ashlar folder (default: this script\'s ../..)')
    ap.add_argument('--out', default=None, help='default: <root>/INDEX.md')
    ap.add_argument('--stdout', action='store_true')
    a = ap.parse_args(argv)
    text = render(collect(a.root))
    if a.stdout:
        sys.stdout.buffer.write(text.encode('utf-8'))
        return 0
    out = a.out or os.path.join(a.root, 'INDEX.md')
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print('%s: %d lines' % (out, text.count('\n')))
    return 0


if __name__ == '__main__':
    sys.exit(main())
