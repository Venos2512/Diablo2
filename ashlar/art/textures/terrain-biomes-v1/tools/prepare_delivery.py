# ----------------------------------------------------------------------------- pipeline
def run(a) -> dict:
    manifest = Path(a.manifest).resolve()
    biome = manifest.parent
    tex_dir = biome / "textures"
    out_dir = biome / f"albedo{a.size}"
    qa_dir = biome / "delivery_qa"
    if out_dir.resolve() == tex_dir.resolve():
        raise SystemExit("refusing: output directory is the immutable textures/ directory")
    jobs = load_manifest(manifest)
    only = {x.strip() for o in a.only for x in o.split(",") if x.strip()}
    unknown = only - {j["id"] for j in jobs}
    if unknown:
        raise SystemExit(f"--only: unknown ids {sorted(unknown)}")

    meta_path = biome / "delivery_metadata.json"
    prev = {}
    if meta_path.is_file() and not a.force:
        try:
            prev = {e["id"]: e for e in json.loads(meta_path.read_text(encoding="utf-8")).get("entries", [])}
        except (OSError, ValueError):
            prev = {}

    entries, src_hashes = [], {}
    for j in jobs:
        jid, prompt = j["id"], j.get("prompt", "")
        raw_p, alb_p = tex_dir / f"{jid}.png", out_dir / f"{jid}.png"
        e = {"id": jid, "biome_id": str(j.get("biome_id", "")), "name_vi": str(j.get("name_vi", "")),
             "material": str(j.get("material", "")), "prompt": prompt, "reference": j.get("reference"),
             "prompt_file": prompt_file_of(biome, jid), "palette_hex": palette_of(prompt),
             "status": "missing", "raw": None, "provenance": read_provenance(biome, jid),
             "delivered": None, "processing": None, "metrics": None}
        entries.append(e)
        if not raw_p.is_file():
            continue
        ok, err = readable_png(raw_p)
        if not ok:
            e.update(status="error", error=f"raw unreadable: {err}", raw={"path": rel(raw_p, biome)})
            continue
        e["raw"] = file_info(raw_p, biome)
        src_hashes[jid] = e["raw"]["sha256"]
        p = prev.get(jid) or {}
        selected = not only or jid in only
        pp, pd = p.get("processing") or {}, p.get("delivered") or {}
        fresh = (alb_p.is_file() and pp.get("source_sha256") == e["raw"]["sha256"]
                 and pp.get("algorithm") == ALGO and pd.get("width") == a.size
                 and pd.get("sha256") == sha256_of(alb_p) and p.get("metrics") is not None)
        if fresh and not (selected and a.force):
            e["processing"], e["metrics"] = p["processing"], p["metrics"]
            e["delivered"] = file_info(alb_p, biome)
            e["status"] = "ready"
            continue
        if not selected:
            if alb_p.is_file():  # delivered earlier from a different source or by another tool: say so
                e["delivered"] = file_info(alb_p, biome)
                e["status"] = "ready"
                e["processing"] = {"note": "not re-processed in this run; metrics unavailable"}
            else:
                e["status"] = "raw_only"
            continue
        try:
            with Image.open(raw_p) as im:
                before, after, info = process_image(im, a.size)
            write_atomic(alb_p, png_bytes(Image.fromarray(after)))
        except Exception as ex:  # noqa: BLE001 - keep the batch going, report per entry
            e.update(status="error", error=f"processing failed: {ex!r}")
            continue
        e["processing"] = {"algorithm": ALGO, "source_sha256": e["raw"]["sha256"], "size": a.size,
                           "resized_from": info["resized_from"], "non_square_source": info["non_square_source"],
                           "flatten": "none", "processed": utc()}
        e["metrics"] = {k: info[k] for k in ("before", "after", "mean_rgb_before", "mean_rgb_after", "max_mean_shift")}
        e["delivered"] = file_info(alb_p, biome)
        e["status"] = "ready"
        print(f'{jid}: edge L-R/T-B {info["before"]["edge_lr"]}/{info["before"]["edge_tb"]} -> '
              f'{info["after"]["edge_lr"]}/{info["after"]["edge_tb"]}  mean shift {info["max_mean_shift"]}')

    for e in entries:  # a texture the pipeline could not show is not "ready"
        if e["status"] == "ready" and not (out_dir / f'{e["id"]}.png').is_file():
            e["status"] = "raw_only" if e["raw"] else "missing"

    counts = {
        "manifest_jobs": len(entries),
        "raw_present": sum(1 for e in entries if e["raw"]),
        "delivered": sum(1 for e in entries if e["status"] == "ready"),
        "missing": sum(1 for e in entries if e["status"] == "missing"),
        "raw_only": sum(1 for e in entries if e["status"] == "raw_only"),
        "errors": sum(1 for e in entries if e["status"] == "error"),
        "biomes_in_manifest": len({e["biome_id"] for e in entries}),
        "biomes_with_texture": len({e["biome_id"] for e in entries if e["status"] in ("ready", "raw_only")}),
    }

    # thumbnails (gallery) + QA sheets are built from what is on disk now
    thumbs, thumbs_small = {}, {}
    for e in entries:
        if e["status"] == "ready":
            src = out_dir / f'{e["id"]}.png'
        elif e["status"] == "raw_only":
            src = tex_dir / f'{e["id"]}.png'
        else:
            continue
        thumbs[e["id"]] = thumb_data_url(src, a.thumb, 88)
        thumbs_small[e["id"]] = thumb_data_url(src, a.compact_thumb, 78)

    sheets = []
    ready = [e for e in entries if e["status"] == "ready"]
    for n in range(0, len(ready), GROUP):
        chunk = ready[n:n + GROUP]
        name = f"repeat3x3_sheet_{n // GROUP + 1:02d}.png"
        cells = [{"id": f'{e["id"]}', "path": str(out_dir / f'{e["id"]}.png'),
                  "lines": [e["material"], edge_line(e["metrics"])]} for e in chunk]
        make_sheet(cells, qa_dir / name, min(4, len(cells)), a.cell,
                   f"terrain-biomes-v1 albedo{a.size} - 3x3 repeat, sheet {n // GROUP + 1} (seams for human review)", True)
        sheets.append({"file": f"delivery_qa/{name}", "ids": [e["id"] for e in chunk]})
    thumb_sheet = None
    if entries:
        cells = []
        for e in entries:
            p = out_dir / f'{e["id"]}.png' if e["status"] == "ready" else (
                tex_dir / f'{e["id"]}.png' if e["status"] == "raw_only" else None)
            cells.append({"id": e["id"], "path": str(p) if p else None,
                          "lines": [e["biome_id"], e["status"].upper() if e["status"] != "ready" else e["material"]]})
        make_sheet(cells, qa_dir / "thumbnails_all.png", 8, 150, f'terrain-biomes-v1 - {len(entries)} manifest entries '
                   f'({counts["delivered"]} delivered, {counts["missing"]} missing)', False)
        thumb_sheet = "delivery_qa/thumbnails_all.png"

    write_atomic(biome / "gallery.html", build_gallery(entries, thumbs, counts, False).encode("utf-8"))
    write_atomic(biome / "gallery.compact.html", build_gallery(entries, thumbs_small, counts, True).encode("utf-8"))

    # originals must still hash identically
    changed = [jid for jid, h in src_hashes.items() if sha256_of(tex_dir / f"{jid}.png") != h]
    meta = {
        "generated": utc(), "tool": "tools/prepare_delivery.py",
        "manifest": {"path": rel(manifest, biome), "sha256": sha256_of(manifest), "jobs": len(jobs)},
        "algorithm": ALGO, "size": a.size,
        "counts": counts, "notes": NOTES,
        "outputs": {"albedo_dir": rel(out_dir, biome), "repeat3x3_sheets": sheets, "thumbnails_sheet": thumb_sheet,
                    "gallery": "gallery.html", "gallery_compact": "gallery.compact.html"},
        "extra_cards": [{"biome_id": BIO25["biome_id"], "name_vi": BIO25["name_vi"], "material": BIO25["material"],
                         "texture": None, "explanation": BIO25["lines"]}],
        "sources_unchanged": not changed, "sources_changed": changed,
        "entries": entries,
    }
    write_atomic(meta_path, json.dumps(meta, indent=2, ensure_ascii=False).encode("utf-8"))
    write_atomic(biome / "DELIVERY_README.txt", readme(counts, a.size).encode("utf-8"))
    print(json.dumps({"counts": counts, "sources_unchanged": not changed}, ensure_ascii=False))
    return meta


def readme(c: dict, size: int) -> str:
    return f"""ASHLAR terrain-biomes-v1 - delivery (seam correction only)
Generated by tools/prepare_delivery.py. Counts at generation time: manifest {c['manifest_jobs']}, raw {c['raw_present']},
delivered {c['delivered']}, missing {c['missing']}, raw-only {c['raw_only']}, errors {c['errors']}.

Pixels   textures/{{id}}.png (Codex originals, never modified) -> LANCZOS resize to {size} -> periodic component of the
         periodic+smooth decomposition (Moisan 2011), per channel -> albedo{size}/{{id}}.png.
         No crossfade ring (prints a square grid), no light flattening, no hue change, nothing painted.
Metrics  delivery_metadata.json: per entry source sha256, edge jump L-R/T-B before/after (mean abs RGB diff of opposite
         edge lines vs neighbouring lines), mean RGB before/after. Metrics are hints; look at delivery_qa/ 3x3 sheets.
Files    gallery.html (full page), gallery.compact.html (fluid, transparent, no title) - both self-contained.
         delivery_qa/repeat3x3_sheet_NN.png (<=12 per sheet), delivery_qa/thumbnails_all.png.
Status   Palettes are lookdev proposals; the 27-biome taxonomy is not approved; Map 1 = Diablo II Act I mood only.
         BIO-25 (Seamless) is a deliberate textureless white explanatory card, not a missing file.
Re-run   python -I tools/prepare_delivery.py   (idempotent: unchanged sources are not reprocessed; --force to redo)
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", default=str(BIOME_DIR / "manifest.json"))
    ap.add_argument("--only", action="append", default=[], help="process only these ids (repeatable/comma)")
    ap.add_argument("--size", type=int, default=1024, help="delivered albedo size (default 1024)")
    ap.add_argument("--thumb", type=int, default=224, help="gallery.html thumbnail px")
    ap.add_argument("--compact-thumb", type=int, default=176, help="gallery.compact.html thumbnail px")
    ap.add_argument("--cell", type=int, default=480, help="px of each 3x3-repeat cell on QA sheets")
    ap.add_argument("--force", action="store_true", help="reprocess even if the source hash is unchanged")
    a = ap.parse_args(argv)
    if a.size < 16:
        raise SystemExit("--size too small")
    run(a)
    return 0


if __name__ == "__main__":
    sys.exit(main())
