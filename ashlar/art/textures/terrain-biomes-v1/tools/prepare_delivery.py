# ----------------------------------------------------------------------------- maths
def periodic(img):
    """Periodic component of the periodic + smooth decomposition (Moisan 2011), per channel: subtracts the smooth
    image that carries the jump across the tile border, so the tile wraps without a seam while every detail stays.
    The generated tiles are already nearly seamless; sw.make_seamless (half-shift cross-fade along a square ring)
    printed that ring into every repeat, which read as a square grid on the ground."""
    h, w = img.shape[:2]
    out = np.empty_like(img)
    q = np.cos(2 * np.pi * np.arange(h) / h)[:, None]
    r = np.cos(2 * np.pi * np.arange(w) / w)[None, :]
    den = 2 * q + 2 * r - 4
    den[0, 0] = 1
    for c in range(img.shape[2]):
        u = img[..., c].astype(np.float64)
        v = np.zeros_like(u)
        v[0, :] += u[-1, :] - u[0, :]
        v[-1, :] += u[0, :] - u[-1, :]
        v[:, 0] += u[:, -1] - u[:, 0]
        v[:, -1] += u[:, 0] - u[:, -1]
        s = np.fft.fft2(v) / den
        s[0, 0] = 0
        out[..., c] = u - np.real(np.fft.ifft2(s))
    return np.clip(out, 0.0, 1.0)


def edge_metrics(arr) -> dict:
    """Mean abs RGB difference (0-255) across the wrap (opposite edge lines) vs between neighbouring lines."""
    a = np.asarray(arr, dtype=np.float64)
    lr = float(np.abs(a[:, 0] - a[:, -1]).mean())
    tb = float(np.abs(a[0] - a[-1]).mean())
    ax = float(np.abs(a[:, 1:] - a[:, :-1]).mean())
    ay = float(np.abs(a[1:] - a[:-1]).mean())
    return {"edge_lr": round(lr, 3), "edge_tb": round(tb, 3), "adjacent_x": round(ax, 3),
            "adjacent_y": round(ay, 3),
            "ratio_lr": round(lr / ax, 2) if ax else None, "ratio_tb": round(tb / ay, 2) if ay else None}


def to_uint8(a):
    return np.clip(np.asarray(a) * 255 + 0.5, 0, 255).astype(np.uint8)


def mean_rgb(arr) -> list[float]:
    return [round(float(x), 2) for x in np.asarray(arr, dtype=np.float64).reshape(-1, 3).mean(0)]


def process_image(img: Image.Image, size: int) -> tuple[np.ndarray, np.ndarray, dict]:
    """Return (before uint8 HxWx3 at `size`, after uint8, info). Never touches any file."""
    rgb = img.convert("RGB")
    orig = rgb.size
    if rgb.size != (size, size):
        rgb = rgb.resize((size, size), Image.LANCZOS)
    before = np.asarray(rgb)
    after = to_uint8(periodic(before.astype(np.float32) / 255.0))
    mb, ma = mean_rgb(before), mean_rgb(after)
    info = {
        "resized_from": list(orig), "non_square_source": orig[0] != orig[1],
        "before": edge_metrics(before), "after": edge_metrics(after),
        "mean_rgb_before": mb, "mean_rgb_after": ma,
        "max_mean_shift": round(max(abs(x - y) for x, y in zip(mb, ma)), 3),
    }
    return before, after, info


# ----------------------------------------------------------------------------- io helpers
def utc() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_atomic(path: Path, data: bytes):
    """tmp + replace, retried: writes on this drive sometimes fail with EINVAL for a moment."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    for attempt in range(20):
        try:
            tmp.write_bytes(data)
            os.replace(tmp, path)
            return
        except OSError:
            if attempt == 19:
                raise
            time.sleep(0.5)


def png_bytes(img: Image.Image) -> bytes:
    buf = io.BytesIO()
    img.save(buf, "PNG")
    return buf.getvalue()


def rel(path: Path, base: Path) -> str:
    try:
        return path.resolve().relative_to(base.resolve()).as_posix()
    except ValueError:
        return str(path)


def ascii_safe(text: str) -> str:
    return unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()


def load_font(size: int):
    for name in ("segoeui.ttf", "arial.ttf", "DejaVuSans.ttf"):
        for base in ("C:/Windows/Fonts", "/usr/share/fonts/truetype/dejavu"):
            p = Path(base) / name
            if p.exists():
                return ImageFont.truetype(str(p), size)
    return ImageFont.load_default()


def fit(text: str, font, width: int) -> str:
    try:
        while len(text) > 1 and font.getlength(text) > width:
            text = text[:-2] + "…" if len(text) > 2 else text[:-1]
    except Exception:  # noqa: BLE001 - font without getlength: leave as is
        pass
    return text


def draw_text(d, xy, text, fill, font):
    try:
        d.text(xy, text, fill=fill, font=font)
    except Exception:  # bitmap fallback font can't take diacritics
        d.text(xy, ascii_safe(text), fill=fill, font=font)


def thumb_data_url(path: Path, px: int, quality: int) -> str:
    with Image.open(path) as im:
        t = im.convert("RGB").resize((px, px), Image.LANCZOS)
    buf = io.BytesIO()
    t.save(buf, "JPEG", quality=quality, subsampling=0, optimize=True)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode("ascii")


# ----------------------------------------------------------------------------- manifest / entries
def load_manifest(path: Path) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    if not isinstance(data, list):
        raise SystemExit(f"{path}: expected a JSON array of jobs")
    seen = set()
    for n, d in enumerate(data):
        if not isinstance(d, dict) or not d.get("id"):
            raise SystemExit(f"{path}[{n}]: job needs an id")
        if d["id"] in seen:
            raise SystemExit(f"{path}: duplicate id {d['id']}")
        seen.add(d["id"])
    return data


def palette_of(prompt: str) -> list[str]:
    out = []
    for m in HEX_RE.findall(prompt or ""):
        m = m.upper()
        if m not in out:
            out.append(m)
    return out


def biome_num(biome_id: str) -> int:
    m = BIOME_NUM_RE.search(biome_id or "")
    return int(m.group(1)) if m else 0


def read_provenance(biome: Path, jid: str) -> dict | None:
    p = biome / "logs" / f"{jid}.provenance.json"
    if not p.is_file():
        return None
    try:
        d = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"file": rel(p, biome), "error": "unreadable"}
    keep = ("source_path", "source_how", "thread_ids", "sha256", "model", "started", "finished",
            "sandbox", "scratch_files")
    return {"file": rel(p, biome), **{k: d[k] for k in keep if k in d}}


def prompt_file_of(biome: Path, jid: str) -> dict | None:
    for name in (f"{jid}.txt", f"{jid}.task.txt"):
        p = biome / "prompts" / name
        if p.is_file():
            return {"path": rel(p, biome), "sha256": sha256_of(p)}
    return None


def file_info(path: Path, biome: Path) -> dict:
    with Image.open(path) as im:
        w, h = im.size
    return {"path": rel(path, biome), "sha256": sha256_of(path), "bytes": path.stat().st_size,
            "width": w, "height": h}


def readable_png(path: Path) -> tuple[bool, str]:
    try:
        with Image.open(path) as im:
            im.load()
        return True, ""
    except Exception as e:  # noqa: BLE001 - report any decode failure
        return False, repr(e)


# ----------------------------------------------------------------------------- QA sheets
def tile3(path: Path, cell: int) -> Image.Image:
    """3x3 repeat of the tile inside a cell x cell square (cell is rounded down to a multiple of 3)."""
    t = cell // 3
    with Image.open(path) as im:
        small = im.convert("RGB").resize((t, t), Image.LANCZOS)
    big = Image.new("RGB", (t * 3, t * 3))
    for x in range(3):
        for y in range(3):
            big.paste(small, (x * t, y * t))
    return big


def make_sheet(cells: list[dict], out: Path, cols: int, cell: int, title: str, repeat3: bool):
    pad, label_h, head_h = 10, 56, 34
    cell = cell // 3 * 3 if repeat3 else cell
    rows = (len(cells) + cols - 1) // cols
    W = pad + cols * (cell + pad)
    H = head_h + rows * (cell + label_h + pad) + pad
    sheet = Image.new("RGB", (W, H), (24, 24, 26))
    d = ImageDraw.Draw(sheet)
    f_big, f_small = load_font(17), load_font(12)
    draw_text(d, (pad, 8), title, (230, 230, 230), f_big)
    for i, c in enumerate(cells):
        r, k = divmod(i, cols)
        x, y = pad + k * (cell + pad), head_h + r * (cell + label_h + pad)
        if c.get("path"):
            if repeat3:
                sheet.paste(tile3(Path(c["path"]), cell), (x, y))
            else:
                with Image.open(c["path"]) as im:
                    sheet.paste(im.convert("RGB").resize((cell, cell), Image.LANCZOS), (x, y))
        else:  # absent output: say so, draw nothing that looks like a texture
            d.rectangle((x, y, x + cell - 1, y + cell - 1), fill=(40, 22, 22), outline=(150, 60, 60))
            draw_text(d, (x + 10, y + cell // 2 - 8), "MISSING", (230, 120, 120), f_big)
        draw_text(d, (x, y + cell + 3), fit(c["id"], f_small, cell), (240, 240, 240), f_small)
        for n, line in enumerate(c.get("lines", [])[:3]):
            draw_text(d, (x, y + cell + 19 + n * 15), fit(line, f_small, cell), (185, 185, 150), f_small)
    write_atomic(out, png_bytes(sheet))


def edge_line(m: dict | None) -> str:
    if not m:
        return "mép: n/a"
    b, a = m["before"], m["after"]
    return f'mép L-R/T-B {b["edge_lr"]}/{b["edge_tb"]} -> {a["edge_lr"]}/{a["edge_tb"]}'


