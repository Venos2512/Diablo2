# ------------------------------------------------------------------ small helpers
def norm(p):
    return os.path.normcase(os.path.abspath(str(p))).replace('\\', '/')


def redact(text):
    for rx in SECRET_RES:
        text = rx.sub(lambda m: (m.group(1) if m.lastindex else '') + '[redacted]', text)
    return text


def resolve(p, base):
    p = Path(p)
    return p if p.is_absolute() else (base / p)


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def png_check(path):
    """Return (ok, width, height, error). Full decode with Pillow if present, else stdlib chunk/CRC/zlib walk."""
    try:
        try:
            from PIL import Image
        except ImportError:
            Image = None
        if Image is not None:
            with Image.open(path) as im:
                if im.format != 'PNG':
                    return False, 0, 0, f'not a PNG (format {im.format})'
                im.load()
                return True, im.width, im.height, ''
        with open(path, 'rb') as f:
            data = f.read()
        if data[:8] != b'\x89PNG\r\n\x1a\n':
            return False, 0, 0, 'bad PNG signature'
        pos, w, h, idat, first, ended, interlace = 8, 0, 0, [], True, False, 0
        while pos + 12 <= len(data):
            n, typ = struct.unpack('>I4s', data[pos:pos + 8])
            body = data[pos + 8:pos + 8 + n]
            crc = struct.unpack('>I', data[pos + 8 + n:pos + 12 + n])[0]
            if len(body) != n or zlib.crc32(typ + body) & 0xffffffff != crc:
                return False, 0, 0, f'corrupt chunk {typ!r}'
            if first:
                if typ != b'IHDR':
                    return False, 0, 0, 'IHDR missing'
                w, h = struct.unpack('>II', body[:8])
                interlace = body[12]
                first = False
            elif typ == b'IDAT':
                idat.append(body)
            elif typ == b'IEND':
                ended = True
                break
            pos += 12 + n
        if not ended or not idat:
            return False, 0, 0, 'truncated PNG (no IEND/IDAT)'
        raw = zlib.decompress(b''.join(idat))
        if not interlace and len(raw) < h:
            return False, 0, 0, 'image data too short'
        return True, w, h, ''
    except Exception as e:  # noqa: BLE001 - any decode problem means "invalid"
        return False, 0, 0, f'{type(e).__name__}: {e}'[:200]


def parse_min_size(s):
    m = re.fullmatch(r'(\d+)x(\d+)', s.strip().lower())
    if not m:
        raise SystemExit(f'--min-size must look like 1024x680, got {s!r}')
    return int(m.group(1)), int(m.group(2))


# ------------------------------------------------------------------ process control
def kill_tree(proc):
    """Kill the child and every descendant. Windows: taskkill /T /F by PID (argument list, no shell)."""
    try:
        if os.name == 'nt':
            tk = Path(os.environ.get('SystemRoot', r'C:\Windows')) / 'System32' / 'taskkill.exe'
            subprocess.run([str(tk) if tk.exists() else 'taskkill', '/PID', str(proc.pid), '/T', '/F'],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=30, check=False)
        else:
            os.killpg(proc.pid, signal.SIGKILL)
    except Exception:  # noqa: BLE001 - fall through to the direct kill
        pass
    try:
        proc.kill()
    except Exception:  # noqa: BLE001
        pass


def kill_all_active():
    with ACTIVE_LOCK:
        procs = list(ACTIVE)
    for p in procs:
        kill_tree(p)


def run_codex(cmd, task_bytes, log_path, env, timeout):
    """Run one session. Returns the exit code, or 'timeout'. The log file is created exclusively."""
    kw = {}
    if os.name == 'nt':
        kw['creationflags'] = subprocess.CREATE_NEW_PROCESS_GROUP
    else:
        kw['start_new_session'] = True
    with open(log_path, 'xb') as log:
        proc = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=log, stderr=subprocess.STDOUT, env=env, **kw)
        with ACTIVE_LOCK:
            ACTIVE.add(proc)
        try:
            proc.communicate(input=task_bytes, timeout=timeout)
            return proc.returncode
        except subprocess.TimeoutExpired:
            kill_tree(proc)
            try:
                proc.wait(timeout=30)
            except Exception:  # noqa: BLE001
                pass
            return 'timeout'
        finally:
            with ACTIVE_LOCK:
                ACTIVE.discard(proc)
            if proc.poll() is None:
                kill_tree(proc)


