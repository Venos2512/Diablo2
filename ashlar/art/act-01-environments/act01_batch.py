def load_manifest(path):
    m = json.loads(Path(path).read_text(encoding='utf-8'))
    base = Path(path).resolve().parent
    jobs = {}
    for j in m['jobs']:
        if j['id'] in jobs:
            raise SystemExit(f"duplicate job id {j['id']}")
        jobs[j['id']] = j
    return m, jobs, base


def validate_manifest(m, jobs, base):
    """Static checks (no writes). Returns a list of error strings."""
    errs = []
    outs, seen_ref = {}, {}
    groups = {g['id']: g for g in m.get('groups', [])}
    for jid, j in jobs.items():
        out = norm(resolve(j['outputPath'], base))
        if out in outs:
            errs.append(f'{jid}: outputPath duplicates {outs[out]}')
        outs[out] = jid
        if j.get('groupId') not in groups:
            errs.append(f"{jid}: unknown groupId {j.get('groupId')}")
        prompt = resolve(j['promptPath'], base)
        if not prompt.is_file():
            errs.append(f'{jid}: promptPath missing {prompt}')
        refs = [norm(resolve(r['path'], base)) for r in j.get('referenceImages', [])]
        for r in j.get('referenceImages', []):
            ok_missing = any(norm(resolve(r['path'], base)) == norm(resolve(jobs[d]['outputPath'], base))
                             for d in j.get('dependsOn', []) if d in jobs)
            if not resolve(r['path'], base).is_file() and not ok_missing:
                errs.append(f"{jid}: reference image missing {r['path']}")
        for d in j.get('dependsOn', []):
            if d not in jobs:
                errs.append(f'{jid}: unknown dependency {d}')
            elif norm(resolve(jobs[d]['outputPath'], base)) not in refs:
                errs.append(f'{jid}: dependency {d} output is not attached as a reference image')
        if prompt.is_file():
            text = prompt.read_text(encoding='utf-8').replace('\\', '/')
            last = -1
            for r in j.get('referenceImages', []):
                idx = text.find(str(r['path']).replace('\\', '/'))
                if idx < 0:
                    errs.append(f"{jid}: reference path not named in prompt text: {r['path']}")
                elif idx < last:
                    errs.append(f"{jid}: reference order in prompt differs from manifest: {r['path']}")
                else:
                    last = idx
        if not j.get('generate', True) and j.get('dependsOn'):
            errs.append(f'{jid}: reused job must not depend on other jobs')
    # counts
    c = m.get('counts', {})
    per = c.get('assetsPerGroup', 6)
    if c.get('groups') != len(groups):
        errs.append(f"counts.groups {c.get('groups')} != {len(groups)}")
    if c.get('jobs') != len(jobs):
        errs.append(f"counts.jobs {c.get('jobs')} != {len(jobs)}")
    if c.get('assets') != per * len(groups):
        errs.append(f"counts.assets {c.get('assets')} != {per * len(groups)}")
    gen = sum(1 for j in jobs.values() if j.get('generate', True))
    if c.get('generateJobs') != gen:
        errs.append(f"counts.generateJobs {c.get('generateJobs')} != {gen}")
    for gid, g in groups.items():
        kinds = sorted(j['kind'] for j in jobs.values() if j.get('groupId') == gid)
        if kinds != ['environment-perspective', 'environment-turnaround']:
            errs.append(f'{gid}: needs exactly one perspective and one turnaround job, has {kinds}')
        pj = jobs.get(f'{gid}_perspective')
        if pj is not None:
            n = len(pj.get('sizeSpec', {}).get('assets', []))
            if n != per or g.get('assetCount') != per:
                errs.append(f'{gid}: expected {per} assets, sizeSpec has {n}, assetCount {g.get("assetCount")}')
            cells = sorted(a['cell'] for a in pj['sizeSpec']['assets'])
            if cells != list(range(1, per + 1)):
                errs.append(f'{gid}: cells are not 1..{per}')
        tj = jobs.get(f'{gid}_turnaround')
        if tj is not None and f'{gid}_perspective' not in tj.get('dependsOn', []):
            errs.append(f'{gid}: turnaround must depend on its perspective')
    # reused originals are never outputs of a generating job
    reused = {norm(resolve(j['outputPath'], base)) for j in jobs.values() if not j.get('generate', True)}
    for j in jobs.values():
        if j.get('generate', True) and norm(resolve(j['outputPath'], base)) in reused:
            errs.append(f"{j['id']}: would write over a reused original")
    # area coverage
    for a in m.get('areaCoverage', []):
        if not a['primaryGroups']:
            errs.append(f"area {a['areaId']} {a['area']}: no primary group")
        for gid in a['primaryGroups'] + a['sharedGroups']:
            if gid not in groups:
                errs.append(f"area {a['areaId']}: unknown group {gid}")
    if c.get('actIAreas') and len(m.get('areaCoverage', [])) != c['actIAreas']:
        errs.append(f"areaCoverage has {len(m.get('areaCoverage', []))} areas, counts.actIAreas {c['actIAreas']}")
    return errs


# ------------------------------------------------------------------ planning
def plan_jobs(selected, jobs, base, minw, minh):
    """Decide an action per selected job. Returns {id: dict(action, wave, note, ...)}."""
    plan = {}

    def out_state(j):
        out = resolve(j['outputPath'], base)
        if not out.exists():
            return 'absent', None
        ok, w, h, err = png_check(out) if out.is_file() else (False, 0, 0, 'not a file')
        if ok and (w < minw or h < minh):
            return 'invalid', f'{w}x{h} below minimum {minw}x{minh}'
        return ('valid', f'{w}x{h}') if ok else ('invalid', err)

    def decide(jid, trail=()):
        if jid in plan:
            return plan[jid]
        j = jobs[jid]
        state, info = out_state(j)
        rec = dict(id=jid, group=j.get('groupId'), kind=j['kind'], out=str(resolve(j['outputPath'], base)),
                   state=state, info=info, wave=0, deps=list(j.get('dependsOn', [])))
        plan[jid] = rec
        if not j.get('generate', True):
            rec['action'] = 'reuse-existing' if state == 'valid' else 'ERROR-reuse-source-bad'
            rec['note'] = 'reused original, never generated or touched' if state == 'valid' else (
                f'reused original is {state}: {info}' if state != 'absent' else 'reused original is missing')
            return rec
        if state == 'valid':
            rec['action'], rec['note'] = 'skip-exists', f'valid PNG {info} already present, kept'
            return rec
        if state == 'invalid':
            rec['action'], rec['note'] = 'ERROR-invalid-existing', f'existing output is not a valid PNG ({info}); preserved, not overwritten, rename it to proceed'
            return rec
        blockers, wave = [], 1
        for d in rec['deps']:
            if d not in jobs:
                blockers.append(f'unknown dependency {d}')
                continue
            dj = jobs[d]
            if d in selected:
                dr = decide(d, trail + (jid,))
                if dr['action'] in ('generate', 'skip-exists', 'reuse-existing'):
                    wave = max(wave, dr['wave'] + 1 if dr['action'] == 'generate' else 1)
                else:
                    blockers.append(f'dependency {d} is {dr["action"]}')
            else:
                dstate, dinfo = out_state(dj)
                if dstate != 'valid':
                    blockers.append(f'dependency {d} output not present/valid ({dstate}) and not selected')
        for r in j.get('referenceImages', []):
            rp = resolve(r['path'], base)
            is_dep_out = any(norm(rp) == norm(resolve(jobs[d]['outputPath'], base)) for d in rec['deps'] if d in jobs)
            if not rp.is_file() and not (is_dep_out and any(d in selected and plan.get(d, {}).get('action') == 'generate' for d in rec['deps'])):
                blockers.append(f"reference image missing: {r['path']}")
        if not resolve(j['promptPath'], base).is_file():
            blockers.append(f"prompt missing: {j['promptPath']}")
        if blockers:
            rec['action'], rec['note'] = 'BLOCKED', '; '.join(blockers)
        else:
            rec['action'], rec['wave'], rec['note'] = 'generate', wave, f'1 built-in image_gen session, wave {wave}'
        return rec

    for jid in selected:
        decide(jid)
    return plan


# ------------------------------------------------------------------ recording
class Recorder:
    def __init__(self, status_path, dry):
        self.path, self.dry = status_path, dry

    def __call__(self, rec):
        rec['time'] = datetime.now().isoformat(timespec='seconds')
        line = json.dumps(rec, ensure_ascii=False)
        with lock:
            if not self.dry:
                self.path.parent.mkdir(parents=True, exist_ok=True)
                with self.path.open('a', encoding='utf-8') as f:
                    f.write(line + '\n')
            print(json.dumps(rec, ensure_ascii=True), flush=True)  # ASCII-only: a cp1252 console must never break the run


def fresh_tag(folder, stem):
    """Smallest run tag ('' , .r2, .r3 ...) for which no sidecar of this job exists yet."""
    k = 1
    while True:
        tag = '' if k == 1 else f'.r{k}'
        if not any((folder / f'{stem}{tag}{s}').exists() or any(folder.glob(f'{stem}{tag}.attempt*{s}'))
                   for s in SIDECAR_SUFFIXES):
            return tag
        k += 1


def select_session_png(session, codex_home, pick_latest):
    """PNGs of EXACTLY this session folder. Returns (chosen_or_None, all_paths, note)."""
    try:
        sid = str(uuid.UUID(session))
    except ValueError:
        return None, [], 'session id is not a UUID'
    gen_dir = codex_home / 'generated_images' / sid
    pngs = sorted(gen_dir.glob('*.png'), key=lambda p: p.stat().st_mtime) if gen_dir.is_dir() else []
    if not pngs:
        return None, [], 'no PNG in this session folder'
    if len(pngs) == 1:
        return pngs[0], pngs, ''
    if pick_latest:
        return pngs[-1], pngs, 'multiple PNGs in session, newest taken (--pick-latest)'
    return None, pngs, 'multiple PNGs in one session: refusing to guess (use --pick-latest after checking them)'


# ------------------------------------------------------------------ one job
def run_job(job, a, ctx, record):
    out = resolve(job['outputPath'], ctx.base)
    jid = job['id']
    base_rec = {'id': jid, 'group': job.get('groupId')}
    if out.exists():  # re-check at run time: another run may have produced it meanwhile
        ok, w, h, err = png_check(out)
        record(dict(base_rec, status='skipped-exists' if ok else 'invalid-existing-preserved', out=str(out),
                    size=f'{w}x{h}' if ok else None, error=None if ok else err))
        return ok
    folder, stem = out.parent, out.stem
    folder.mkdir(parents=True, exist_ok=True)
    task = HEADER + resolve(job['promptPath'], ctx.base).read_text(encoding='utf-8')
    tag = fresh_tag(folder, stem)
    for name, content in ((f'{stem}{tag}.task.txt', task),
                          (f'{stem}{tag}.prompt.txt', resolve(job['promptPath'], ctx.base).read_text(encoding='utf-8'))):
        with open(folder / name, 'x', encoding='utf-8', newline='') as f:
            f.write(content)
    refs = [str(resolve(r['path'], ctx.base)) for r in job.get('referenceImages', [])]
    for attempt in range(1, a.attempts + 1):
        if stop.is_set():
            record(dict(base_rec, status='not-started (stopped)'))
            return False
        atag = tag + ('' if attempt == 1 else f'.attempt{attempt}')
        log_path = folder / f'{stem}{atag}.generation.log'
        result_path = folder / f'{stem}{atag}.result.txt'
        cmd = [ctx.node, str(ctx.codex_js), 'exec', '--enable', 'image_generation', '-m', a.model,
               '-s', 'workspace-write', '-C', str(ctx.workdir)]
        for ref in refs:
            cmd += ['-i', ref]
        cmd += ['-o', str(result_path), '-']
        env = {k: v for k, v in os.environ.items() if k not in CHILD_ENV_STRIP}
        env['CODEX_HOME'] = str(ctx.codex_home)
        record(dict(base_rec, attempt=attempt, status='started', refs=len(refs)))
        t0 = time.time()
        rc = run_codex(cmd, task.encode('utf-8'), log_path, env, a.timeout)
        text = log_path.read_text(encoding='utf-8', errors='replace')
        m = SESSION_RE.search(text)
        session = m.group(1) if m else None
        rec = dict(base_rec, attempt=attempt, rc=rc, sec=round(time.time() - t0), session=session)
        chosen, allp, note = select_session_png(session, ctx.codex_home, a.pick_latest) if session else (None, [], 'no session id in log')
        rec['images'] = len(allp)
        if chosen is None and allp:
            rec.update(status='multiple-images-not-copied', sessionImages=[p.name for p in allp], note=note)
            record(rec)
            return False
        if chosen is not None:
            ok, w, h, err = png_check(chosen)
            if not ok or w < ctx.minw or h < ctx.minh:
                rec.update(status='invalid-generated', src=str(chosen), size=f'{w}x{h}',
                           error=err or f'below minimum {ctx.minw}x{ctx.minh}')
                record(rec)
                return False
            try:
                with open(chosen, 'rb') as s, open(out, 'xb') as d:  # exclusive create: never overwrites
                    shutil.copyfileobj(s, d)
            except FileExistsError:
                rec.update(status='exists-after-run', out=str(out))
                record(rec)
                return True
            digest = sha256(chosen)
            if sha256(out) != digest:
                out.unlink()
                rec.update(status='copy-mismatch-removed', src=str(chosen))
                record(rec)
                return False
            rec.update(status='ok', src=str(chosen), out=str(out), size=f'{w}x{h}', bytes=out.stat().st_size,
                       sha256=digest, aspect=round(w / h, 3), note=note or None)
            record(rec)
            return True
        tail = redact(text[-1500:])  # the task text is echoed at the top of the log, so only the tail is inspected
        rec['status'] = 'timeout' if rc == 'timeout' else 'limit' if LIMIT_RE.search(tail) else \
            'capacity' if CAPACITY_RE.search(tail) else 'no-image'
        rec['tail'] = tail[-500:]
        record(rec)
        if rec['status'] == 'limit':
            stop.set()
            return False
        if rec['status'] == 'capacity' and attempt < a.attempts:
            end = time.time() + a.backoff
            while time.time() < end and not stop.is_set():
                time.sleep(1)
    return False


# ------------------------------------------------------------------ main
def find_codex_js(arg):
    cands = [arg] if arg else []
    cands += [os.environ.get('CODEX_JS')]
    if os.environ.get('APPDATA'):
        cands.append(Path(os.environ['APPDATA']) / 'npm/node_modules/@openai/codex/bin/codex.js')
    cands.append(Path.home() / '.npm-global/lib/node_modules/@openai/codex/bin/codex.js')
    for c in cands:
        if c and Path(c).is_file():
            return Path(c)
    return Path(arg) if arg else None


def build_parser():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--manifest', default=str(HERE / 'manifest.json'))
    ap.add_argument('--status', help='status JSONL path (default: <manifest dir>/_runs/batch_<date>.jsonl); appended, never truncated')
    ap.add_argument('--codex-home', help='CODEX_HOME for the child sessions (default: manifest runner.codexHome)')
    ap.add_argument('--codex-js', help='path to @openai/codex/bin/codex.js (default: $CODEX_JS or the npm global install)')
    ap.add_argument('--node', help='node executable (default: first on PATH)')
    ap.add_argument('--workdir', help='codex -C directory (default: manifest workdir)')
    ap.add_argument('--model', help='default: manifest runner.model (gpt-6-astra)')
    ap.add_argument('--jobs', nargs='+', metavar='ID', help='job ids, in run order')
    ap.add_argument('--groups', nargs='+', metavar='GID', help='select every job of these groups (e.g. A05 A06)')
    ap.add_argument('--kinds', nargs='+', choices=['perspective', 'turnaround'], help='filter selection by sheet kind')
    ap.add_argument('--all', action='store_true', help='select every job (required for a full real run)')
    ap.add_argument('--with-deps', action='store_true', help='also select the unfinished dependencies of selected jobs')
    ap.add_argument('--parallel', type=int, default=None, help='concurrent sessions (default 3, max 8)')
    ap.add_argument('--attempts', type=int, default=None, help='fresh sessions per job (default 1, max 5)')
    ap.add_argument('--timeout', type=int, default=None, help='seconds per session, 60..7200 (default 1200)')
    ap.add_argument('--backoff', type=int, default=90, help='seconds to wait after a capacity error before the next attempt (0..600)')
    ap.add_argument('--min-size', default='1024x680', help='smallest accepted PNG, WxH (default 1024x680)')
    ap.add_argument('--pick-latest', action='store_true', help='if one session produced several PNGs take the newest instead of refusing')
    ap.add_argument('--dry-run', action='store_true', help='show every selected job and its action; no writes, no generation')
    ap.add_argument('--check', action='store_true', help='validate the manifest and coverage only; no writes, no generation')
    ap.add_argument('--show-cmd', action='store_true', help='with --dry-run: print the exact codex argument list per job')
    return ap


def main(argv=None):
    ap = build_parser()
    a = ap.parse_args(argv)
    m, jobs, base = load_manifest(a.manifest)
    rd = m.get('runner', {})
    a.parallel = min(max(1, a.parallel if a.parallel is not None else rd.get('defaultParallel', 3)), 8)
    a.attempts = min(max(1, a.attempts if a.attempts is not None else rd.get('defaultAttempts', 1)), 5)
    a.timeout = min(max(60, a.timeout if a.timeout is not None else rd.get('defaultTimeoutSeconds', 1200)), 7200)
    a.backoff = min(max(0, a.backoff), 600)
    a.model = a.model or rd.get('model', 'gpt-6-astra')
    minw, minh = parse_min_size(a.min_size)

    errs = validate_manifest(m, jobs, base)
    print(f"manifest: {len(m['groups'])} groups, {len(jobs)} jobs, {m['counts'].get('assets')} assets, "
          f"{len(m.get('areaCoverage', []))} areas; validation errors: {len(errs)}")
    for e in errs:
        print('  MANIFEST ERROR:', e)
    if a.check:
        for ar in m.get('areaCoverage', []):
            print(f"  area {ar['areaId']:>5} {ar['area']:<28} primary={','.join(ar['primaryGroups']) or '-':<5} shared={','.join(ar['sharedGroups']) or '-'}")
        return 1 if errs else 0

    # selection
    if a.jobs:
        unknown = [j for j in a.jobs if j not in jobs]
        if unknown:
            raise SystemExit(f'unknown job ids: {unknown}')
        selected = list(dict.fromkeys(a.jobs))
    else:
        selected = list(jobs)
        if a.groups:
            bad = [g for g in a.groups if g not in {x["id"] for x in m['groups']}]
            if bad:
                raise SystemExit(f'unknown group ids: {bad}')
            selected = [j for j in selected if jobs[j].get('groupId') in a.groups]
        elif not (a.all or a.dry_run):
            raise SystemExit('refusing a real run without a selection: pass --jobs, --groups or --all (or use --dry-run)')
    if a.kinds:
        selected = [j for j in selected if jobs[j]['kind'].split('-', 1)[1] in a.kinds]
    if a.with_deps:
        extra, stack = [], list(selected)
        while stack:
            for d in jobs[stack.pop()].get('dependsOn', []):
                if d not in selected and d not in extra:
                    extra.append(d)
                    stack.append(d)
        selected = extra + selected
    if not selected:
        raise SystemExit('nothing selected')
    # dependencies first within the same list
    selected.sort(key=lambda j: len(jobs[j].get('dependsOn', [])))

    ctx = Ctx()
    ctx.base, ctx.minw, ctx.minh = base, minw, minh
    ctx.workdir = Path(a.workdir or m.get('workdir') or os.getcwd())
    ch = a.codex_home or os.environ.get('ASHLAR_CODEX_HOME') or rd.get('codexHome')
    ctx.codex_home = Path(ch) if ch else None
    ctx.node = a.node or shutil.which('node')
    ctx.codex_js = find_codex_js(a.codex_js)

    tool_errs = []
    if not ctx.node:
        tool_errs.append('node not found on PATH (use --node)')
    if not ctx.codex_js or not Path(ctx.codex_js).is_file():
        tool_errs.append(f'codex.js not found ({ctx.codex_js}); use --codex-js')
    if ctx.codex_home is None or not ctx.codex_home.is_dir():
        tool_errs.append(f'CODEX_HOME folder not found ({ctx.codex_home}); use --codex-home')
    if not ctx.workdir.is_dir():
        tool_errs.append(f'workdir not found ({ctx.workdir}); use --workdir')

    plan = plan_jobs(selected, jobs, base, minw, minh)
    status_path = Path(a.status) if a.status else base / '_runs' / f'batch_{datetime.now():%Y-%m-%d}.jsonl'
    print(f"mode: {'DRY-RUN (no writes, no generation)' if a.dry_run else 'REAL RUN'}; parallel={a.parallel} attempts={a.attempts} "
          f"timeout={a.timeout}s model={a.model}")
    print(f'codex_home={ctx.codex_home} codex_js={ctx.codex_js} workdir={ctx.workdir}')
    print(f'status file: {status_path}')
    counts = {}
    for jid in selected:
        p = plan[jid]
        counts[p['action']] = counts.get(p['action'], 0) + 1
        print(f"  [{p['action']:<22}] {jid:<16} wave={p['wave']} {p['kind'].split('-', 1)[1]:<11} -> {p['out']}  | {p['note']}")
        if a.dry_run and a.show_cmd:
            j = jobs[jid]
            cmd = [str(ctx.node), str(ctx.codex_js), 'exec', '--enable', 'image_generation', '-m', a.model, '-s',
                   'workspace-write', '-C', str(ctx.workdir)]
            for r in j.get('referenceImages', []):
                cmd += ['-i', str(resolve(r['path'], base))]
            cmd += ['-o', '<sidecar .result.txt>', '-']
            print('      argv:', json.dumps(cmd, ensure_ascii=True))
    print('plan:', ', '.join(f'{k}={v}' for k, v in sorted(counts.items())))
    plan_errs = [p for p in plan.values() if p['action'].startswith('ERROR') or p['action'] == 'BLOCKED']
    if tool_errs:
        for t in tool_errs:
            print(('  WARNING (dry-run): ' if a.dry_run else '  ERROR: ') + t)
    if a.dry_run:
        return 1 if (errs or plan_errs) else 0
    if tool_errs:
        return 2
    if errs:
        print('refusing to run: fix the manifest errors above first')
        return 1

    record = Recorder(status_path, dry=False)
    results = {}

    def guarded(jid):
        try:
            results[jid] = run_job(jobs[jid], a, ctx, record)
        except Exception as e:  # noqa: BLE001 - report and keep the pool going
            results[jid] = False
            record({'id': jid, 'status': 'runner-error', 'error': redact(repr(e))})

    todo = [j for j in selected if plan[j]['action'] == 'generate']
    for j in selected:
        p = plan[j]
        if p['action'] != 'generate':
            record({'id': j, 'group': jobs[j].get('groupId'), 'status': p['action'].lower(), 'note': p['note'], 'out': p['out']})
    try:
        waves = sorted({plan[j]['wave'] for j in todo})
        for w in waves:
            batch = [j for j in todo if plan[j]['wave'] == w]
            runnable = []
            for jid in batch:
                bad = [d for d in jobs[jid].get('dependsOn', [])
                       if not resolve(jobs[d]['outputPath'], base).is_file()]
                if bad:
                    record({'id': jid, 'status': 'blocked-dependency', 'missing': bad})
                else:
                    runnable.append(jid)
            with ThreadPoolExecutor(a.parallel) as pool:
                for jid in runnable:
                    pool.submit(guarded, jid)
    except KeyboardInterrupt:
        stop.set()
        kill_all_active()
        print('INTERRUPTED: child process trees killed', flush=True)
        return 1
    finally:
        kill_all_active()
    print('BATCH DONE', flush=True)
    return 0 if (all(results.get(j) for j in todo) and not plan_errs) else 1


if __name__ == '__main__':
    sys.exit(main())
