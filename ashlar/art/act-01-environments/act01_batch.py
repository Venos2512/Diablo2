"""Portable manifest-driven batch runner for ASHLAR concept briefs (adapted from the Map 01 scratch runner).

One fresh `codex exec` session per job (model gpt-6-astra, BUILT-IN image_gen only: `--enable image_generation`),
reference images attached with `-i`, then the PNG generated by THAT exact session is validated and copied
(exclusive create, never overwriting) to the job's outputPath. No image_gen.py, no API keys, no shell.

  python act01_batch.py --dry-run                       # inspect every job, writes nothing, generates nothing
  python act01_batch.py --check                         # manifest + coverage validation only
  python act01_batch.py --groups A05 A06 --parallel 3   # real run (needs --jobs / --groups / --all)

Defaults come from the manifest "runner" block and can be overridden on the command line.
Exit code: 0 = ok, 1 = problems reported (preflight/validation/generation), 2 = bad usage or missing tooling.
"""
