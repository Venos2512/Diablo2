def img_data_url(img: Image.Image, px: int, quality: int = 86) -> str:
    buf = io.BytesIO()
    img.convert("RGB").resize((px, px), Image.LANCZOS).save(buf, "JPEG", quality=quality, subsampling=0, optimize=True)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode("ascii")


def previews(normal_path: Path, albedo_path: Path) -> dict[str, Image.Image]:
    with Image.open(normal_path) as im:
        n = np.asarray(im.convert("RGB"))
    with Image.open(albedo_path) as im:
        al = np.asarray(im.convert("RGB"))
    if al.shape[:2] != n.shape[:2]:
        al = np.asarray(Image.fromarray(al).resize(n.shape[1::-1], Image.LANCZOS))
    v = normalize(decode_rgb(n))
    return {"albedo": Image.fromarray(al), "normal": Image.fromarray(n),
            "grey": Image.fromarray(lit_grey(v)), "lit": Image.fromarray(lit_albedo(v, al))}


def corner_crops(normal_path: Path, px: int = CORNER_PX) -> tuple[Image.Image, Image.Image]:
    """2x2 tiled crop of px x px centred on the tile corner at 1:1: (normal map, grey lit) - seams at real scale."""
    with Image.open(normal_path) as im:
        n = np.asarray(im.convert("RGB"))
    h, w = n.shape[:2]
    big = np.tile(n, (2, 2, 1))
    py, px_ = min(px, 2 * h), min(px, 2 * w)
    crop = big[h - py // 2:h - py // 2 + py, w - px_ // 2:w - px_ // 2 + px_]
    return Image.fromarray(crop), Image.fromarray(lit_grey(normalize(decode_rgb(crop))))


def tile3_img(img: Image.Image, cell: int) -> Image.Image:
    t = cell // 3
    small = img.convert("RGB").resize((t, t), Image.LANCZOS)
    big = Image.new("RGB", (t * 3, t * 3))
    for x in range(3):
        for y in range(3):
            big.paste(small, (x * t, y * t))
    return big


def grid_sheet(cells: list[dict], out: Path, cols: int, cell: int, title: str, repeat3: bool = False):
    """cells: {label, img (PIL or None), note (text drawn when img is None), lines}."""
    pad, label_h, head_h = 10, 52, 34
    cell = cell // 3 * 3 if repeat3 else cell
    rows = (len(cells) + cols - 1) // cols
    W, H = pad + cols * (cell + pad), head_h + rows * (cell + label_h + pad) + pad
    sheet = Image.new("RGB", (W, H), (24, 24, 26))
    d = ImageDraw.Draw(sheet)
    f_big, f_small = pd.load_font(17), pd.load_font(12)
    pd.draw_text(d, (pad, 8), title, (230, 230, 230), f_big)
    for i, c in enumerate(cells):
        r, k = divmod(i, cols)
        x, y = pad + k * (cell + pad), head_h + r * (cell + label_h + pad)
        if c.get("img") is not None:
            sheet.paste(tile3_img(c["img"], cell) if repeat3 else c["img"].convert("RGB").resize((cell, cell), Image.LANCZOS), (x, y))
        else:
            d.rectangle((x, y, x + cell - 1, y + cell - 1), fill=(40, 22, 22), outline=(150, 60, 60))
            pd.draw_text(d, (x + 10, y + cell // 2 - 8), c.get("note", "MISSING"), (230, 120, 120), f_big)
        pd.draw_text(d, (x, y + cell + 3), pd.fit(c["label"], f_small, cell), (240, 240, 240), f_small)
        for n, line in enumerate(c.get("lines", [])[:2]):
            pd.draw_text(d, (x, y + cell + 19 + n * 15), pd.fit(line, f_small, cell), (185, 185, 150), f_small)
    pd.write_atomic(out, pd.png_bytes(sheet))


