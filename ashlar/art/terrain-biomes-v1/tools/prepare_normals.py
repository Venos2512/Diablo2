def readme(c: dict, size: int) -> str:
    return f"""ASHLAR terrain-biomes-v1 - normal map delivery (resize, convention, registration, seam)
Generated by tools/prepare_normals.py. Counts at generation time: manifest {c['manifest_jobs']}, raw {c['raw_present']},
delivered {c['delivered']}, missing {c['missing']}, raw-only {c['raw_only']}, errors {c['errors']}.

Source   normal/textures/{{id}}.png: Codex gpt-6-astra image_gen, albedo{size}/{{id}}.png attached as edit target (never modified).
         normal/selection.json may name another raw per id (e.g. reruns/textures/*_v2.png; paths relative to normal/):
         it is used instead of the v1 file (a missing selected raw is an error, no silent fallback) and shown as a badge.
Output   normal{size}/{{id}}.png  RGB8, OpenGL tangent space (+Y up = three.js), flat = #8080FF, unit vectors, nz >= 0.05.
Pixels   Order matters: the seam is fixed BEFORE anything moves content.
         1) decode at the NATIVE size, normalise, read slopes p, q (OpenGL), subtract mean(p), mean(q) (raw maps carry
            1-16 deg of uniform tilt; the removed tilt is recorded, warning above 8 deg).
         2) seam: periodic component (Moisan 2011) of the slopes p, q at native size, rebuild (-p, q, 1).
         3) periodic-aware resize: wrap-tiled 3x3 mosaic, float vector components LANCZOS-resized (3n -> 3*size, exact for
            any n and size), centre tile cropped, renormalise.
         4) green-channel convention: r = curl_DX/curl_GL at sigma 2 (RMS(curl)/RMS(div) of the slopes), d = relief_GL -
            relief_DX (integrated height vs albedo luma). r <= 0.75 -> DirectX (flip G); r >= 1.33 -> OpenGL; flag
            convention_conflict when relief disagrees by > 0.3 (curl wins). 0.75 < r < 1.33: d <= -0.4 DirectX,
            d >= +0.4 OpenGL, else OpenGL + convention_ambiguous.
         5) registration to the albedo: shift = median of the usable 4x4 block phase-correlation shifts (low-passed,
            peak z >= 8); applied (exact periodic Fourier translation) only if >= 6 blocks are usable, >= 60% of them are
            within 1 px (Euclidean) of the median, |shift| <= 8 px and the edge NCC at the shifted position is >= NCC(0)+0.01.
            Otherwise not shifted (registration_uncertain when the blocks disagree; a plain warning when a block-agreeing
            shift >= 0.5 px is rejected by the NCC-gain gate or the 8 px limit); --no-register disables.
            Shift = np.roll of the normal content (+y down, +x right). The edge-NCC search (+-8 px, sub-pixel) is a
            diagnostic only. Residual 4x4 block shifts after registration are reported.
         6) slopes -> (-p, q, 1) rebuild, RGB8. nz floor: slopes are read with nz clamped at 0.15, so the delivered nz is
            >= ~0.15 in practice (steeper than ~81 deg is flattened); the 0.05 guard only covers overshoot.
         Nothing is painted. The relief sign of the delivered map (NCC with albedo luma) is only reported, never flipped
         automatically; inside the convention test relief is a secondary cue that cannot override a confident curl result.
         Seam metrics: wrap-pair jump L-R/T-B and a band metric (worst adjacent-line ratio within +-8 lines of the wrap;
         warning above 1.8). A raw with its own raised-difference band along the edges keeps a softer residual - reported,
         not cross-faded (a cross-fade ring prints a grid).
Metrics  normal_metadata.json: raw sha256 + provenance + selection, removed mean slope, steps, convention ratios, registration (shift, NCC before/after,
         block residuals), relief NCC, tilt mean/p95/near-flat, seam edge jump before/after (8-bit RGB), vector length, warnings.
         Metrics are hints; look at normal_qa/ (compare sheets, 3x3 repeats, thumbnails_all.png).
Files    normal_qa/tile_corners_NN.png: 2x2 tiled crop around the tile corner at 1:1 (normal + grey lit) to see seams.
         gallery.normals.html (self-contained, no script). BIO-25 (Seamless) has no texture, so no normal map.
three.js texture.colorSpace = THREE.NoColorSpace (linear data); tune material.normalScale per biome from the tilt mean/p95.
Preview  lit = light from upper-left l = normalize(-1, 1, 1.1): grey = 0.25+0.75*max(0,n.l); albedo*(0.3+0.85*max(0,n.l)).
Status   Not integrated in any engine; the 27-biome taxonomy and palettes are not approved.
Re-run   python -I tools/prepare_normals.py   (idempotent: unchanged raw + albedo are not reprocessed; --force to redo)
"""


# ----------------------------------------------------------------------------- pipeline
def read_provenance(biome: Path, jid: str, rel_path: str | None = None) -> dict | None:
    """Provenance json (UTF-8), default normal/logs/{id}.provenance.json, reduced to the fields worth keeping."""
    p = biome / "normal" / (rel_path or f"logs/{jid}.provenance.json")
    if not p.is_file():
        return None
    try:
        d = json.loads(p.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return {"file": pd.rel(p, biome), "error": "unreadable"}
    keep = ("source_path", "source_how", "thread_ids", "sha256", "model", "started", "finished", "sandbox", "reference")
    return {"file": pd.rel(p, biome), **{k: d[k] for k in keep if k in d}}


def prompt_file_of(biome: Path, jid: str, rel_path: str | None = None) -> dict | None:
    names = [rel_path] if rel_path else [f"prompts/{jid}.txt", f"prompts/{jid}.task.txt"]
    for name in names:
        p = biome / "normal" / name
        if p.is_file():
            return {"path": pd.rel(p, biome), "sha256": pd.sha256_of(p)}
    return None


VERSION_RE = re.compile(r"_(v\d+)\.[A-Za-z0-9]+$")


def load_selection(biome: Path) -> dict[str, dict]:
    """normal/selection.json: {id: {raw, provenance, prompt, why[, version]}} (keys starting with "_" are comments).
    Paths are relative to normal/. A listed id uses that raw instead of normal/textures/{id}.png."""
    p = biome / "normal" / "selection.json"
    if not p.is_file():
        return {}
    try:
        d = json.loads(p.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as ex:
        raise SystemExit(f"{p}: unreadable selection ({ex})")
    out = {}
    for k, v in d.items():
        if k.startswith("_"):
            continue
        if not isinstance(v, dict) or not v.get("raw"):
            raise SystemExit(f"{p}: entry {k} needs a 'raw' path")
        m = VERSION_RE.search(str(v["raw"]))
        out[k] = {"raw": str(v["raw"]), "provenance": v.get("provenance"), "prompt": v.get("prompt"),
                  "why": str(v.get("why", "")), "version": str(v.get("version") or (m.group(1) if m else "selected"))}
    return out


def run(a) -> dict:
    biome = Path(a.biome).resolve()
    manifest = Path(a.manifest).resolve() if a.manifest else biome / "normal" / "manifest.json"
    raw_dir = biome / "normal" / "textures"
    alb_dir = biome / f"albedo{a.size}"
    out_dir = biome / f"normal{a.size}"
    qa_dir = biome / "normal_qa"
    if out_dir.resolve() in (raw_dir.resolve(), alb_dir.resolve()):
        raise SystemExit("refusing: output directory is an input directory")
    jobs = pd.load_manifest(manifest)
    selection = load_selection(biome)
    stray = set(selection) - {j["id"] for j in jobs}
    if stray:
        raise SystemExit(f"selection.json: unknown ids {sorted(stray)}")
    only = {x.strip() for o in a.only for x in o.split(",") if x.strip()}
    unknown = only - {j["id"] for j in jobs}
    if unknown:
        raise SystemExit(f"--only: unknown ids {sorted(unknown)}")

    meta_path = biome / "normal_metadata.json"
    prev = {}
    if meta_path.is_file():      # always loaded: --force only bypasses the freshness check of the selected ids
        try:
            prev = {e["id"]: e for e in json.loads(meta_path.read_text(encoding="utf-8")).get("entries", [])}
        except (OSError, ValueError):
            prev = {}

    entries, src_hashes = [], {}
    for j in jobs:
        jid = j["id"]
        sel = selection.get(jid)
        raw_p = (biome / "normal" / sel["raw"]) if sel else raw_dir / f"{jid}.png"
        alb_p, out_p = alb_dir / f"{jid}.png", out_dir / f"{jid}.png"
        e = {"id": jid, "biome_id": str(j.get("biome_id", "")), "name_vi": str(j.get("name_vi", "")),
             "material": str(j.get("material", "")), "status": "missing", "raw": None,
             "albedo": None, "selection": ({"raw": sel["raw"], "version": sel["version"], "why": sel["why"]} if sel else None),
             "provenance": read_provenance(biome, jid, sel["provenance"] if sel else None),
             "prompt_file": prompt_file_of(biome, jid, sel["prompt"] if sel else None), "delivered": None, "processing": None, "metrics": None,
             "warnings": []}
        entries.append(e)
        if not raw_p.is_file():
            if sel:  # never fall back silently to the v1 file
                e.update(status="error", error=f"selected raw {pd.rel(raw_p, biome)} missing (selection.json); no fallback")
            continue
        ok, err = pd.readable_png(raw_p)
        if not ok:
            e.update(status="error", error=f"raw unreadable: {err}", raw={"path": pd.rel(raw_p, biome)})
            continue
        e["raw"] = pd.file_info(raw_p, biome)
        src_hashes[jid] = [(raw_p, e["raw"]["sha256"])]
        if not alb_p.is_file():
            e.update(status="error", error=f"albedo {pd.rel(alb_p, biome)} missing; cannot register")
            continue
        e["albedo"] = {"path": pd.rel(alb_p, biome), "sha256": pd.sha256_of(alb_p)}
        src_hashes[jid].append((alb_p, e["albedo"]["sha256"]))
        selected = not only or jid in only
        p = prev.get(jid) or {}
        pp, pdl = p.get("processing") or {}, p.get("delivered") or {}
        fresh = (out_p.is_file() and pp.get("source_sha256") == e["raw"]["sha256"] and pp.get("algorithm") == ALGO
                 and pp.get("size") == a.size and pp.get("register") == (not a.no_register)
                 and pp.get("albedo_sha256") == e["albedo"]["sha256"] and pdl.get("sha256") == pd.sha256_of(out_p)
                 and p.get("metrics") is not None)
        if fresh and not (selected and a.force):
            e["processing"], e["metrics"], e["warnings"] = p["processing"], p["metrics"], p.get("warnings", [])
            e["delivered"] = pd.file_info(out_p, biome)
            e["status"] = "ready"
            continue
        if not selected:
            if out_p.is_file():
                e["delivered"] = pd.file_info(out_p, biome)
                e["status"] = "ready"
                e["processing"] = {"note": "not re-processed in this run"}
                e["metrics"], e["warnings"] = p.get("metrics"), p.get("warnings", [])
            else:
                e["status"] = "raw_only"
            continue
        try:
            with Image.open(raw_p) as im:
                raw = np.asarray(im.convert("RGB"))
            with Image.open(alb_p) as im:
                al = im.convert("RGB")
                if al.size != (a.size, a.size):
                    al = al.resize((a.size, a.size), Image.LANCZOS)
            out, info = process_normal(raw, np.asarray(al), a.size, not a.no_register)
            pd.write_atomic(out_p, pd.png_bytes(Image.fromarray(out)))
        except Exception as ex:  # noqa: BLE001 - keep the batch going, report per entry
            e.update(status="error", error=f"processing failed: {ex!r}")
            continue
        e["processing"] = {"algorithm": ALGO, "source_sha256": e["raw"]["sha256"], "albedo_sha256": e["albedo"]["sha256"],
                           "size": a.size, "register": not a.no_register, "steps": info.pop("steps"),
                           "processed": pd.utc()}
        e["warnings"] = info.pop("warnings")
        e["metrics"] = info
        e["delivered"] = pd.file_info(out_p, biome)
        e["status"] = "ready"
        c, r = info["convention"], info["registration"]
        print(f'{jid}: conv {c["decision"]} r {c["r_s0"]}/{c["r_s2"]} relief GL/DX {c["relief_gl"]}/{c["relief_dx"]} {",".join(c["flags"])}'
              f' | shift {r["shift_sy"]:+.2f},{r["shift_sx"]:+.2f} {r["decision"]} NCC {r["ncc_before"]}->{r["ncc_after"]}'
              f' | relief {info["relief_ncc"]:+.2f} | warnings {len(e["warnings"])}')

    for e in entries:
        if e["status"] == "ready" and not (out_dir / f'{e["id"]}.png').is_file():
            e["status"] = "raw_only" if e["raw"] else "missing"

    counts = {
        "manifest_jobs": len(entries),
        "raw_present": sum(1 for e in entries if e["raw"]),
        "delivered": sum(1 for e in entries if e["status"] == "ready"),
        "missing": sum(1 for e in entries if e["status"] == "missing"),
        "raw_only": sum(1 for e in entries if e["status"] == "raw_only"),
        "errors": sum(1 for e in entries if e["status"] == "error"),
        "with_warnings": sum(1 for e in entries if e["warnings"]),
    }

    # previews + QA sheets are rebuilt from what is on disk now
    ready = [e for e in entries if e["status"] == "ready"]
    pv, thumbs = {}, {}
    for e in ready:
        pv[e["id"]] = previews(out_dir / f'{e["id"]}.png', alb_dir / f'{e["id"]}.png')
        thumbs[e["id"]] = {k: img_data_url(pv[e["id"]][k], a.thumb) for k in ("albedo", "normal", "lit")}

    sheets = {"compare": [], "normals_repeat3x3": [], "lit_repeat3x3": [], "tile_corners": [], "thumbnails": None}
    for n in range(0, len(ready), GROUP_CMP):
        chunk, name = ready[n:n + GROUP_CMP], f"compare_sheet_{n // GROUP_CMP + 1:02d}.png"
        cells = []
        for e in chunk:
            m = short_metrics(e["metrics"])
            for k, lab, lines in (("albedo", "albedo", [e["material"]]), ("normal", "normal OpenGL", m[:2] if m else []),
                                  ("grey", "grey lit", m[2:3] if m else []), ("lit", "lit albedo", m[3:4] if m else [])):
                cells.append({"label": f'{e["id"]} · {lab}', "img": pv[e["id"]][k], "lines": lines})
        grid_sheet(cells, qa_dir / name, 4, a.cell,
                   f"terrain-biomes-v1 normal{a.size} - albedo | normal | grey lit | lit albedo, sheet {n // GROUP_CMP + 1}", False)
        sheets["compare"].append({"file": f"normal_qa/{name}", "ids": [e["id"] for e in chunk]})
    for n in range(0, len(ready), GROUP_REP):
        chunk = ready[n:n + GROUP_REP]
        for key, kind, tag in (("normals_repeat3x3", "normal", "normal"), ("lit_repeat3x3", "lit", "lit albedo")):
            name = f"{key}_sheet_{n // GROUP_REP + 1:02d}.png"
            cells = [{"label": e["id"], "img": pv[e["id"]][kind],
                      "lines": [e["material"], short_metrics(e["metrics"])[3] if e["metrics"] else ""]} for e in chunk]
            grid_sheet(cells, qa_dir / name, min(4, len(cells)), a.cell,
                       f"terrain-biomes-v1 {tag} - 3x3 repeat, sheet {n // GROUP_REP + 1} (seams for human review)", True)
            sheets[key].append({"file": f"normal_qa/{name}", "ids": [e["id"] for e in chunk]})
    for n in range(0, len(ready), GROUP_CORNER):
        chunk, name = ready[n:n + GROUP_CORNER], f"tile_corners_{n // GROUP_CORNER + 1:02d}.png"
        cells = []
        for e in chunk:
            nc, gc = corner_crops(out_dir / f'{e["id"]}.png')
            band = e["metrics"]["seam"]["band_after"]["max"] if e.get("metrics") else "?"
            cells.append({"label": f'{e["id"]} · normal', "img": nc, "lines": [f"band x{band}"]})
            cells.append({"label": f'{e["id"]} · grey lit', "img": gc, "lines": []})
        grid_sheet(cells, qa_dir / name, 4, CORNER_PX,
                   f"terrain-biomes-v1 normal{a.size} - 2x2 tiled crop around the tile corner, 1:1, sheet {n // GROUP_CORNER + 1}", False)
        sheets["tile_corners"].append({"file": f"normal_qa/{name}", "ids": [e["id"] for e in chunk]})
    if entries:
        cells = []
        for e in entries:
            if e["id"] in pv:
                cells.append({"label": e["id"], "img": pv[e["id"]]["normal"], "lines": [e["biome_id"], e["material"]]})
            else:
                cells.append({"label": e["id"], "img": None, "note": "ERROR" if e["status"] == "error" else "MISSING",
                              "lines": [e["biome_id"], e["status"].upper()]})
        grid_sheet(cells, qa_dir / "thumbnails_all.png", 8, 150,
                   f'terrain-biomes-v1 - {len(entries)} manifest entries, normal maps ({counts["delivered"]} delivered, '
                   f'{counts["missing"]} missing)', False)
        sheets["thumbnails"] = "normal_qa/thumbnails_all.png"

    pd.write_atomic(biome / "gallery.normals.html", build_gallery(entries, thumbs, counts).encode("utf-8"))

    raw_changed = [jid for jid, srcs in src_hashes.items() if pd.sha256_of(srcs[0][0]) != srcs[0][1]]
    albedo_changed = [jid for jid, srcs in src_hashes.items() if len(srcs) > 1 and pd.sha256_of(srcs[1][0]) != srcs[1][1]]
    inputs_changed = sorted(set(raw_changed) | set(albedo_changed))
    meta = {
        "generated": pd.utc(), "tool": "tools/prepare_normals.py",
        "manifest": {"path": pd.rel(manifest, biome), "sha256": pd.sha256_of(manifest), "jobs": len(jobs)},
        "algorithm": ALGO, "size": a.size, "register": not a.no_register,
        "parameters": {"light": [-1.0, 1.0, 1.1], "nz_slope_floor": NZ_SLOPE, "nz_min": NZ_MIN, "max_shift_px": MAX_SHIFT,
                       "min_ncc_gain": MIN_GAIN, "block_agree_px": BLOCK_AGREE_PX, "block_min_usable": BLOCK_MIN_USABLE, "block_min_fraction": BLOCK_MIN_FRACTION, "block_peak_usable": PEAK_USABLE,
                       "convention_rule": (f"r = curl_DX/curl_GL (sigma 2), d = relief_GL - relief_DX: r <= {CONV_R_DX:g} -> DirectX "
                                           f"(conflict if d > {CONV_D_CONFLICT:g}); r >= {CONV_R_GL:g} -> OpenGL (conflict if d < "
                                           f"-{CONV_D_CONFLICT:g}); else d <= -{CONV_D_DECIDE:g} DirectX, d >= {CONV_D_DECIDE:g} "
                                           f"OpenGL, otherwise OpenGL + ambiguous"),
                       "convention_thresholds": {"r_directx_max": CONV_R_DX, "r_opengl_min": CONV_R_GL,
                                                 "d_conflict": CONV_D_CONFLICT, "d_decide": CONV_D_DECIDE},
                       "seam_band": {"k": BAND_K, "warn_ratio": BAND_WARN}, "trusted_shift_warn_px": TRUSTED_SHIFT_WARN_PX,
                       "block_warn_px": BLOCK_WARN_PX},
        "counts": counts, "notes": NOTES,
        "outputs": {"normal_dir": pd.rel(out_dir, biome), "qa": sheets, "gallery": "gallery.normals.html"},
        "extra_cards": [{"biome_id": "BIO-25", "texture": None, "explanation": BIO25_NOTE}],
        "sources_unchanged": not inputs_changed, "sources_changed": inputs_changed,
        "raw_sources_unchanged": not raw_changed, "albedo_sources_unchanged": not albedo_changed,
        "entries": entries,
    }
    pd.write_atomic(meta_path, json.dumps(meta, indent=2, ensure_ascii=False).encode("utf-8"))
    pd.write_atomic(biome / "NORMALS_README.txt", readme(counts, a.size).encode("utf-8"))
    print(json.dumps({"counts": counts, "sources_unchanged": not inputs_changed}, ensure_ascii=False))
    return meta


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--biome", default=str(BIOME_DIR), help="terrain-biomes-v1 folder (default: this tool's parent)")
    ap.add_argument("--manifest", default=None, help="job list (default: <biome>/normal/manifest.json)")
    ap.add_argument("--only", action="append", default=[], help="process only these ids (repeatable/comma)")
    ap.add_argument("--size", type=int, default=1024, help="delivered normal map size (default 1024)")
    ap.add_argument("--thumb", type=int, default=200, help="gallery thumbnail px")
    ap.add_argument("--cell", type=int, default=256, help="px of each cell on QA sheets")
    ap.add_argument("--force", action="store_true", help="reprocess even if the raw hash is unchanged")
    ap.add_argument("--no-register", action="store_true", help="measure the registration but do not apply it")
    a = ap.parse_args(argv)
    if a.size < 16:
        raise SystemExit("--size too small")
    run(a)
    return 0


if __name__ == "__main__":
    sys.exit(main())
