# ----------------------------------------------------------------------------- maths
def decode_rgb(arr) -> np.ndarray:
    """uint8 HxWx3 -> float64 vectors n = rgb/255*2-1 (not normalised)."""
    return np.asarray(arr, dtype=np.float64) / 255.0 * 2.0 - 1.0


def normalize(v: np.ndarray) -> np.ndarray:
    ln = np.sqrt((v * v).sum(-1, keepdims=True))
    out = v / np.maximum(ln, 1e-12)
    flat = ln[..., 0] < 1e-9
    if flat.any():
        out[flat] = (0.0, 0.0, 1.0)
    return out


def resize_vec(v: np.ndarray, size: int) -> np.ndarray:
    """Resample the three components as float images (PIL mode F, LANCZOS) and renormalise. Not done in 8-bit RGB."""
    h, w = v.shape[:2]
    if (h, w) != (size, size):
        v = np.stack([np.asarray(Image.fromarray(v[..., c].astype(np.float32), "F").resize((size, size), Image.LANCZOS),
                                 dtype=np.float64) for c in range(3)], -1)
    return normalize(v)


def resize_vec_periodic(v: np.ndarray, size: int) -> np.ndarray:
    """Resize a PERIODIC vector field to size x size without clamped borders: the field is tiled 3x3 (one full tile of
    wrap padding on every side), the mosaic is resized by the same factor (3n -> 3*size, exact for ANY n and size) and the
    centre tile is cropped, so every output pixel sees the true wrapped neighbourhood. Float components, LANCZOS, then
    renormalise. Works per axis, so a non-square source is fine."""
    h, w = v.shape[:2]
    if (h, w) == (size, size):
        return normalize(v)
    mosaic = np.tile(v, (3, 3, 1))
    comps = []
    for c in range(3):
        big = Image.fromarray(mosaic[..., c].astype(np.float32), "F").resize((3 * size, 3 * size), Image.LANCZOS)
        comps.append(np.asarray(big, dtype=np.float64)[size:2 * size, size:2 * size])
    return normalize(np.stack(comps, -1))


def band_ratio(arr, k: int = BAND_K) -> dict:
    """Seam band metric. For rows and columns: d[i] = mean abs difference between line i and line i+1 (all channels);
    ratio = d / median(d over the interior pairs). Reports the worst ratio among the 2k pairs within +-k lines of the wrap
    (pair -1 is the wrap pair last->first; pairs are named by the first line, negative = counted from the end) and, as a
    reference, the median over interior windows of the same size of their worst ratio (what a texture without a seam
    shows by itself). A seam that was carried inside the tile by a shift shows as a ratio well above that reference."""
    a = np.asarray(arr, dtype=np.float64)
    out = {}
    for name, axis in (("rows", 0), ("cols", 1)):
        n = a.shape[axis]
        other = tuple(i for i in range(a.ndim) if i != axis)
        d = np.abs(np.roll(a, -1, axis) - a).mean(axis=other)            # d[i]: line i -> i+1, d[n-1] is the wrap pair
        base = max(float(np.median(d[:n - 1])), 0.05)
        ratio = d / base
        idx = np.concatenate([np.arange(n - k, n), np.arange(0, k)])
        worst = int(idx[int(np.argmax(ratio[idx]))])
        win = 2 * k
        ref = [float(ratio[i:i + win].max()) for i in range(k, n - 1 - win, win)]
        out[name] = round(float(ratio[idx].max()), 2)
        out[f"{name}_pair"] = worst if worst < k else worst - n
        out[f"{name}_interior_ref"] = round(float(np.median(ref)), 2) if ref else None
    out["max"] = max(out["rows"], out["cols"])
    return out


def slopes(v: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """OpenGL slopes of the height field: p = dh/dcol = -nx/nz, q = dh/drow = +ny/nz (nz floored at NZ_SLOPE)."""
    nz = np.maximum(v[..., 2], NZ_SLOPE)
    return -v[..., 0] / nz, v[..., 1] / nz


def remove_mean_slope(v: np.ndarray) -> tuple[np.ndarray, dict]:
    """A tileable height field has zero mean slope: subtract the mean of p and of q, rebuild, renormalise."""
    p, q = slopes(v)
    mp, mq = float(p.mean()), float(q.mean())
    deg = float(np.degrees(np.arctan(np.hypot(mp, mq))))
    return from_slopes(p - mp, q - mq), {"mean_p": round(mp, 4), "mean_q": round(mq, 4), "tilt_deg": round(deg, 2)}


def from_slopes(p: np.ndarray, q: np.ndarray) -> np.ndarray:
    """n ~ (-p, q, 1), normalised; slope magnitude capped so that nz >= NZ_MIN."""
    cap = np.sqrt(1.0 / NZ_MIN ** 2 - 1.0)
    m = np.hypot(p, q)
    k = np.where(m > cap, cap / np.maximum(m, 1e-12), 1.0)
    p, q = p * k, q * k
    return normalize(np.stack([-p, q, np.ones_like(p)], -1))


def gauss(a: np.ndarray, sigma: float) -> np.ndarray:
    """Periodic gaussian blur of a 2D array (FFT)."""
    a = np.asarray(a, dtype=np.float64)
    if sigma <= 0:
        return a.copy()
    h, w = a.shape
    fy, fx = np.fft.fftfreq(h)[:, None], np.fft.rfftfreq(w)[None, :]
    k = np.exp(-2.0 * np.pi ** 2 * sigma ** 2 * (fx * fx + fy * fy))
    return np.fft.irfft2(np.fft.rfft2(a) * k, s=(h, w))


def ddx(a):
    return (np.roll(a, -1, 1) - np.roll(a, 1, 1)) / 2.0


def ddy(a):
    return (np.roll(a, -1, 0) - np.roll(a, 1, 0)) / 2.0


def periodic_component(u: np.ndarray) -> np.ndarray:
    """Periodic component of the periodic + smooth decomposition (Moisan 2011) of a 2D array, no clipping."""
    u = np.asarray(u, dtype=np.float64)
    h, w = u.shape
    q = np.cos(2 * np.pi * np.arange(h) / h)[:, None]
    r = np.cos(2 * np.pi * np.arange(w) / w)[None, :]
    den = 2 * q + 2 * r - 4
    den[0, 0] = 1
    v = np.zeros_like(u)
    v[0, :] += u[-1, :] - u[0, :]
    v[-1, :] += u[0, :] - u[-1, :]
    v[:, 0] += u[:, -1] - u[:, 0]
    v[:, -1] += u[:, 0] - u[:, -1]
    s = np.fft.fft2(v) / den
    s[0, 0] = 0
    return u - np.real(np.fft.ifft2(s))


def luma_of(rgb_u8: np.ndarray) -> np.ndarray:
    return (np.asarray(rgb_u8, dtype=np.float64) / 255.0) @ LUMA


def ncc(a: np.ndarray, b: np.ndarray) -> float:
    a, b = a - a.mean(), b - b.mean()
    d = float(np.sqrt((a * a).sum() * (b * b).sum()))
    return float((a * b).sum() / d) if d > 1e-15 else 0.0


# ---- convention
def curl_div_ratio(p: np.ndarray, q: np.ndarray, sigma: float) -> float:
    """RMS(curl) / RMS(div) of the slope field (p, q), periodic central differences. A true gradient has curl 0."""
    if sigma > 0:
        p, q = gauss(p, sigma), gauss(q, sigma)
    curl = ddx(q) - ddy(p)
    div = ddx(p) + ddy(q)
    rc, rd = float(np.sqrt((curl ** 2).mean())), float(np.sqrt((div ** 2).mean()))
    if rd < 1e-12:
        return 1.0 if rc < 1e-12 else float("inf")
    return rc / rd


def detect_convention(p: np.ndarray, q_gl: np.ndarray, luma: np.ndarray) -> dict:
    """Green-channel convention from two cues. q_gl is the slope read with the OpenGL sign (+ny/nz); the DirectX
    reading is -q_gl.
      r = ratio_DX / ratio_GL at sigma 2, ratio = RMS(curl)/RMS(div)  (< 1: the DirectX reading is the integrable one;
          sigma 0 is noise-dominated and only recorded; 1-D features have curl 0 either way => r ~ 1, r == 1 if both vanish)
      d = relief_GL - relief_DX, relief = band-passed NCC of the integrated height with the albedo luma
    r <= 0.75 -> DirectX (flip G), flag convention_conflict if d > +0.3;  r >= 1.33 -> OpenGL, flag convention_conflict if
    d < -0.3 (a confident curl result is physics and wins over the material-dependent "raised = lighter" prior);
    0.75 < r < 1.33 (inconclusive) -> DirectX if d <= -0.4, OpenGL if d >= +0.4, else OpenGL + convention_ambiguous."""
    rat = {"gl": {"s0": curl_div_ratio(p, q_gl, 0), "s2": curl_div_ratio(p, q_gl, 2)},
           "dx": {"s0": curl_div_ratio(p, -q_gl, 0), "s2": curl_div_ratio(p, -q_gl, 2)}}

    def ratio(s):
        gl, dx = rat["gl"][s], rat["dx"][s]
        if gl < 1e-9 and dx < 1e-9:
            return 1.0
        return dx / max(gl, 1e-9)
    r0, r2 = ratio("s0"), ratio("s2")
    rel_gl, rel_dx = relief_ncc(p, q_gl, luma), relief_ncc(p, -q_gl, luma)
    d = rel_gl - rel_dx
    flags = []
    if r2 <= CONV_R_DX:
        decision = "directx"
        if d > CONV_D_CONFLICT:
            flags.append("convention_conflict")
    elif r2 >= CONV_R_GL:
        decision = "opengl"
        if d < -CONV_D_CONFLICT:
            flags.append("convention_conflict")
    elif d <= -CONV_D_DECIDE:
        decision = "directx"
    else:
        decision = "opengl"
        if d < CONV_D_DECIDE:
            flags.append("convention_ambiguous")
    return {"ratio_gl": {k: round(x, 3) for k, x in rat["gl"].items()},
            "ratio_dx": {k: round(x, 3) for k, x in rat["dx"].items()},
            "r_s0": round(r0, 3), "r_s2": round(r2, 3),
            "relief_gl": round(rel_gl, 3), "relief_dx": round(rel_dx, 3), "d": round(d, 3),
            "decision": decision, "flags": flags, "flipped": decision == "directx"}


# ---- relief sign
def integrate_slopes(p: np.ndarray, q: np.ndarray) -> np.ndarray:
    """Frankot-Chellappa height from slopes (p = dh/dcol, q = dh/drow), periodic FFT; zero mean."""
    h, w = p.shape
    kx = 2 * np.pi * np.fft.fftfreq(w)[None, :]
    ky = 2 * np.pi * np.fft.fftfreq(h)[:, None]
    den = kx * kx + ky * ky
    den[0, 0] = 1
    hh = (-1j * kx * np.fft.fft2(p) - 1j * ky * np.fft.fft2(q)) / den
    hh[0, 0] = 0
    return np.real(np.fft.ifft2(hh))


def relief_ncc(p: np.ndarray, q: np.ndarray, luma: np.ndarray) -> float:
    """NCC of the band-passed (gauss 3 - gauss 40) integrated height with the band-passed albedo luma.
    Positive = raised is lighter."""
    def bp(a):
        return gauss(a, 3) - gauss(a, 40)
    return ncc(bp(integrate_slopes(p, q)), bp(luma))


# ---- registration
def edge_maps(p: np.ndarray, q: np.ndarray, luma: np.ndarray, sigma: float = 1.5) -> tuple[np.ndarray, np.ndarray]:
    """(eN, eL): slope-vector magnitude of the normal map and gradient magnitude of the albedo luma, both blurred."""
    eN = np.hypot(gauss(p, sigma), gauss(q, sigma))
    bl = gauss(luma, sigma)
    return eN, np.hypot(ddx(bl), ddy(bl))


def parabolic(cm: float, c0: float, cp: float) -> float:
    """Sub-sample offset (-0.5..0.5) of the peak through three equally spaced samples."""
    den = cm - 2 * c0 + cp
    if den >= -1e-15:
        return 0.0
    return float(np.clip(0.5 * (cm - cp) / den, -0.5, 0.5))


def estimate_shift(eN: np.ndarray, eL: np.ndarray, max_shift: int = MAX_SHIFT) -> dict:
    """Best roll (sy, sx) of eN onto eL: NCC for every circular shift at once (c[s] = sum a(r - s) b(r))."""
    a, b = eN - eN.mean(), eL - eL.mean()
    norm = float(np.sqrt((a * a).sum() * (b * b).sum()))
    if norm < 1e-15:
        return {"sy": 0.0, "sx": 0.0, "ncc_before": 0.0, "ncc_best": 0.0, "peak_int": (0, 0)}
    c = np.real(np.fft.ifft2(np.conj(np.fft.fft2(a)) * np.fft.fft2(b))) / norm
    h, w = c.shape
    best, bsy, bsx = -2.0, 0, 0
    for sy in range(-max_shift, max_shift + 1):
        for sx in range(-max_shift, max_shift + 1):
            val = c[sy % h, sx % w]
            if val > best:
                best, bsy, bsx = float(val), sy, sx
    dy = parabolic(c[(bsy - 1) % h, bsx % w], best, c[(bsy + 1) % h, bsx % w])
    dx = parabolic(c[bsy % h, (bsx - 1) % w], best, c[bsy % h, (bsx + 1) % w])
    return {"sy": bsy + dy, "sx": bsx + dx, "ncc_before": float(c[0, 0]), "ncc_best": best,
            "peak_int": (bsy, bsx)}


def fourier_shift(a: np.ndarray, sy: float, sx: float) -> np.ndarray:
    """Periodic translation by (sy, sx) px, same sign as np.roll: out[r, c] = in[r - sy, c - sx] (shift theorem)."""
    h, w = a.shape[:2]
    ph = np.exp(-2j * np.pi * (np.fft.fftfreq(h)[:, None] * sy + np.fft.fftfreq(w)[None, :] * sx))
    if a.ndim == 2:
        return np.real(np.fft.ifft2(np.fft.fft2(a) * ph))
    return np.stack([np.real(np.fft.ifft2(np.fft.fft2(a[..., c]) * ph)) for c in range(a.shape[2])], -1)


def phase_shift(a: np.ndarray, b: np.ndarray, lowpass: float = PHASE_LOWPASS) -> tuple[float, float, float]:
    """Hann-windowed phase correlation, whitened then low-passed (gaussian, `lowpass` cycles/px) so that pixel noise
    does not decide: returns (sy, sx, z) with roll(a, (sy, sx)) ~ b; z = peak / std of the correlation surface
    (~4-6 for unrelated noise, >> 8 for a real common shift)."""
    h, w = a.shape
    win = np.hanning(h)[:, None] * np.hanning(w)[None, :]
    fa, fb = np.fft.fft2((a - a.mean()) * win), np.fft.fft2((b - b.mean()) * win)
    r = np.conj(fa) * fb
    r /= np.abs(r) + 1e-9 * (np.abs(r).max() + 1e-30)
    if lowpass > 0:
        r *= np.exp(-(np.fft.fftfreq(h)[:, None] ** 2 + np.fft.fftfreq(w)[None, :] ** 2) / (2 * lowpass ** 2))
    c = np.real(np.fft.ifft2(r))
    iy, ix = np.unravel_index(int(np.argmax(c)), c.shape)
    peak = float(c[iy, ix])
    dy = parabolic(c[(iy - 1) % h, ix], peak, c[(iy + 1) % h, ix])
    dx = parabolic(c[iy, (ix - 1) % w], peak, c[iy, (ix + 1) % w])
    sy = (iy + h // 2) % h - h // 2 + dy
    sx = (ix + w // 2) % w - w // 2 + dx
    return float(sy), float(sx), peak / (float(c.std()) + 1e-15)


def block_shifts(eN: np.ndarray, eL: np.ndarray, grid: int = 4) -> list[tuple[float, float, float]]:
    """(sy, sx, z) of the phase correlation of every grid x grid block."""
    h, w = eN.shape
    bh, bw = h // grid, w // grid
    return [phase_shift(eN[by * bh:(by + 1) * bh, bx * bw:(bx + 1) * bw], eL[by * bh:(by + 1) * bh, bx * bw:(bx + 1) * bw])
            for by in range(grid) for bx in range(grid)]


def block_residuals(eN: np.ndarray, eL: np.ndarray, grid: int = 4) -> dict:
    """Residual shift per block; only blocks with a usable peak (z >= PEAK_USABLE) count."""
    blocks = block_shifts(eN, eL, grid)
    shifts = [(sy, sx) for sy, sx, z in blocks if z >= PEAK_USABLE]
    out = {"grid": grid, "usable_blocks": len(shifts), "blocks": grid * grid,
           "peak_z_median": round(float(np.median([z for _, _, z in blocks])), 1)}
    if shifts:
        s = np.array(shifts)
        mag = np.hypot(s[:, 0], s[:, 1])
        out.update(median_sy=round(float(np.median(s[:, 0])), 2), median_sx=round(float(np.median(s[:, 1])), 2),
                   max_abs=round(float(mag.max()), 2), median_abs=round(float(np.median(mag)), 2))
    else:
        out.update(median_sy=None, median_sx=None, max_abs=None, median_abs=None)
    return out


def block_consensus(blocks: list[tuple[float, float, float]]) -> dict:
    """Registration shift from the 4x4 blocks: the MEDIAN of the usable block shifts (hann-windowed, low-passed phase
    correlation, peak z >= PEAK_USABLE). Trusted if >= BLOCK_MIN_USABLE blocks are usable and >= 60% of them lie within
    BLOCK_AGREE_PX (Euclidean) of that median. The whitened phase correlation is a better estimator than the broad,
    bevel-skewed edge-magnitude NCC peak (measured: BIO14 NCC -4.15 px vs blocks -2.74 px, all blocks mutually
    within ~0.3 px), so the NCC search stays a reported diagnostic only."""
    use = np.array([(by, bx) for by, bx, z in blocks if z >= PEAK_USABLE], dtype=np.float64).reshape(-1, 2)
    out = {"usable": len(use), "agree": 0, "agree_fraction": 0.0, "within_px": BLOCK_AGREE_PX,
           "median_sy": None, "median_sx": None, "trusted": False}
    if len(use) == 0:
        return out
    med = np.median(use, 0)
    agree = int((np.hypot(use[:, 0] - med[0], use[:, 1] - med[1]) <= BLOCK_AGREE_PX).sum())
    out.update(agree=agree, agree_fraction=round(agree / len(use), 3), median_sy=round(float(med[0]), 3),
               median_sx=round(float(med[1]), 3),
               trusted=len(use) >= BLOCK_MIN_USABLE and agree >= BLOCK_MIN_FRACTION * len(use))
    return out


def register(v: np.ndarray, luma: np.ndarray, apply: bool = True) -> tuple[np.ndarray, dict]:
    """Register the normal map to the albedo by translation (np.roll sign: out[r,c] = in[r-sy, c-sx]).
    Shift = median of the usable 4x4 block phase-correlation shifts. Applied (periodic Fourier translation of the
    vectors) only if >= 6 blocks are usable, >= 60% of those lie within 1 px (Euclidean) of the median, |shift| <= 8 and the
    edge NCC at the shifted position is >= NCC(0) + 0.01 (a shift that makes the overlap worse is never applied).
    Otherwise not shifted; 'registration_uncertain' when the blocks do not give a coherent answer.
    The integer/sub-pixel edge-NCC search is kept as a diagnostic (ncc_shift_*).
    Edge magnitude is invariant to the green flip, so this may run before or after it."""
    p, q = slopes(v)
    eN, eL = edge_maps(p, q, luma)
    est = estimate_shift(eN, eL)
    cons = block_consensus(block_shifts(eN, eL))
    sy = cons["median_sy"] if cons["median_sy"] is not None else 0.0
    sx = cons["median_sx"] if cons["median_sx"] is not None else 0.0
    info = {"shift_sy": round(sy, 3), "shift_sx": round(sx, 3), "shift_source": "median of usable 4x4 block phase correlations",
            "convention": "np.roll applied to the normal content: out[r,c]=in[r-sy,c-sx]; +sy down, +sx right",
            "ncc_shift_sy": round(est["sy"], 3), "ncc_shift_sx": round(est["sx"], 3),
            "ncc_before": round(est["ncc_before"], 4), "ncc_best_integer": round(est["ncc_best"], 4),
            "block_agreement": cons, "applied": False, "uncertain": False, "decision": ""}
    out, eN_after = v, eN
    if not cons["trusted"]:
        info["uncertain"] = True
        info["decision"] = (f"rejected: uncertain, {cons['agree']}/{cons['usable']} usable blocks within "
                            f"{BLOCK_AGREE_PX:g} px of their median (need >= {BLOCK_MIN_USABLE} usable, "
                            f"{BLOCK_MIN_FRACTION:.0%} agreeing)")
    elif max(abs(sy), abs(sx)) > MAX_SHIFT:
        info["decision"] = f"rejected: |shift| > {MAX_SHIFT}"
    else:
        cand = normalize(fourier_shift(v, sy, sx))
        cp, cq = slopes(cand)
        eN_c, _ = edge_maps(cp, cq, luma)
        n_c = ncc(eN_c, eL)
        info["ncc_candidate"] = round(n_c, 4)
        if n_c - est["ncc_before"] < MIN_GAIN:
            info["decision"] = f"rejected: NCC gain < {MIN_GAIN}"
        elif not apply:
            info["decision"] = "disabled (--no-register)"
        else:
            out, eN_after = cand, eN_c
            info["applied"], info["decision"] = True, "applied"
    info["ncc_after"] = round(ncc(eN_after, eL), 4)
    info["block_residual"] = block_residuals(eN_after, eL)
    return out, info


# ---- seam, encoding, previews
def seam_fix(v: np.ndarray) -> np.ndarray:
    p, q = slopes(v)
    return from_slopes(periodic_component(p), periodic_component(q))


def encode(v: np.ndarray) -> np.ndarray:
    return np.clip(np.round((v * 0.5 + 0.5) * 255.0), 0, 255).astype(np.uint8)


def lit_term(v: np.ndarray) -> np.ndarray:
    return np.maximum(0.0, v @ LIGHT)


def lit_grey(v: np.ndarray) -> np.ndarray:
    g = np.clip(0.25 + 0.75 * lit_term(v), 0, 1)
    return pd.to_uint8(np.repeat(g[..., None], 3, -1))


def lit_albedo(v: np.ndarray, albedo_u8: np.ndarray) -> np.ndarray:
    k = (0.3 + 0.85 * lit_term(v))[..., None]
    return pd.to_uint8(np.clip(np.asarray(albedo_u8, dtype=np.float64) / 255.0 * k, 0, 1))


def tilt_stats(v: np.ndarray) -> dict:
    t = np.degrees(np.arccos(np.clip(v[..., 2], 0, 1)))
    return {"mean_deg": round(float(t.mean()), 2), "p95_deg": round(float(np.percentile(t, 95)), 2),
            "near_flat_fraction": round(float((t < NEAR_FLAT_DEG).mean()), 4), "near_flat_deg": NEAR_FLAT_DEG}


def length_stats(v: np.ndarray) -> dict:
    ln = np.sqrt((v * v).sum(-1))
    return {"mean": round(float(ln.mean()), 4), "p5": round(float(np.percentile(ln, 5)), 4),
            "min": round(float(ln.min()), 4), "max": round(float(ln.max()), 4)}


def process_normal(raw_rgb: np.ndarray, albedo_rgb: np.ndarray, size: int, do_register: bool = True) -> tuple[np.ndarray, dict]:
    """Pure function: raw uint8 normal map + delivered albedo (uint8, size x size) -> (uint8 normal map, info).
    Order (the seam is fixed BEFORE anything moves content, so no shift can carry a seam into the tile):
      native-size decode -> mean slope removal -> Moisan periodic slopes -> periodic resize -> convention -> registration
      (exact Fourier shift of a periodic map) -> nz floor rebuild -> encode."""
    warnings, steps = [], []
    raw_v = decode_rgb(raw_rgb)
    h0, w0 = raw_rgb.shape[:2]
    info = {"raw_vector_length": length_stats(raw_v), "resized_from": [w0, h0], "non_square_source": h0 != w0}
    if info["non_square_source"]:
        warnings.append("non-square source was stretched to a square")
    rl = info["raw_vector_length"]
    if rl["mean"] < 0.9 or rl["mean"] > 1.1:
        warnings.append(f"raw vector length mean {rl['mean']} far from 1 (not a normal map?)")
    luma = luma_of(albedo_rgb)

    # 1-2. native size: uniform tilt out, then the seam (periodic component of the slopes)
    v, bias = remove_mean_slope(normalize(raw_v))
    info["mean_slope_removed"] = bias
    steps.append(f"mean slope removed at native {w0}x{h0}: p {bias['mean_p']:+.4f}, q {bias['mean_q']:+.4f} "
                 f"({bias['tilt_deg']} deg uniform tilt)")
    if bias["tilt_deg"] > BIAS_WARN_DEG:
        warnings.append(f"large uniform tilt bias removed ({bias['tilt_deg']} deg; mean p {bias['mean_p']:+.3f}, q {bias['mean_q']:+.3f})")
    v = seam_fix(v)
    steps.append("seam at native size: periodic component (Moisan 2011) of slopes p, q; rebuild (-p, q, 1); normalise")

    # 3. periodic-aware resize
    v = resize_vec_periodic(v, size)
    steps.append(f"resize {w0}x{h0} -> {size}: periodic (3x3 wrap-tiled mosaic, float vector components, LANCZOS, renormalise)")

    # 4. convention (Moisan is linear, so the seam fix commutes with the flip)
    p, q = slopes(v)
    conv = detect_convention(p, q, luma)
    info["convention"] = conv
    if conv["flipped"]:
        v[..., 1] *= -1
        steps.append("flip green channel (DirectX -> OpenGL)")
        warnings.append(f"DirectX green channel detected (curl DX/GL r={conv['r_s2']}, relief d={conv['d']}); flipped to OpenGL")
    if "convention_ambiguous" in conv["flags"]:
        warnings.append(f"convention_ambiguous: curl DX/GL r={conv['r_s2']}, relief GL-DX d={conv['d']}; kept OpenGL (prior)")
    if "convention_conflict" in conv["flags"]:
        warnings.append(f"convention_conflict: curl decides {conv['decision']} (r={conv['r_s2']}) but relief disagrees "
                        f"(d={conv['d']}); curl wins")
    steps.append(f"convention: {conv['decision']}" + (f" ({', '.join(conv['flags'])})" if conv["flags"] else ""))

    # 5. registration on the periodic map
    v, reg = register(v, luma, apply=do_register)
    info["registration"] = reg
    steps.append("registration: " + (f"fourier shift sy={reg['shift_sy']} sx={reg['shift_sx']}" if reg["applied"]
                                     else f"not applied ({reg['decision']})"))
    if reg["uncertain"]:
        ba = reg["block_agreement"]
        warnings.append(f"registration_uncertain: 4x4 blocks do not agree on a shift ({ba['agree']}/{ba['usable']} usable blocks "
                        f"within {BLOCK_AGREE_PX:g} px of the median {reg['shift_sy']},{reg['shift_sx']}; NCC diagnostic "
                        f"{reg['ncc_shift_sy']},{reg['ncc_shift_sx']}); not shifted")
    elif (not reg["applied"] and reg["block_agreement"]["trusted"] and do_register
          and max(abs(reg["shift_sy"]), abs(reg["shift_sx"])) >= TRUSTED_SHIFT_WARN_PX):
        warnings.append(f"registration: trusted block shift {reg['shift_sy']},{reg['shift_sx']} px not applied "
                        f"({reg['decision']})")
    res = reg["block_residual"]
    if res["max_abs"] is not None and res["max_abs"] > BLOCK_WARN_PX and not reg["uncertain"]:
        warnings.append(f"block residual shift up to {res['max_abs']} px after registration (non-uniform misalignment)")
    if res["usable_blocks"] == 0:
        warnings.append("no usable block for the residual shift check")

    # 6. nz floor (slope clamp NZ_SLOPE), encode
    v = from_slopes(*slopes(v))
    steps.append("rebuild (-p, q, 1) through the nz floor; normalise; encode RGB8")
    out = encode(v)
    wrap_before, wrap_after = pd.edge_metrics(raw_rgb), pd.edge_metrics(out)
    band_before, band_after = band_ratio(raw_rgb), band_ratio(out)
    info["seam"] = {"before": wrap_before, "after": wrap_after, "measured_on": "8-bit RGB; before = raw at native size",
                    "band_before": band_before, "band_after": band_after, "band_k": BAND_K}
    if band_after["max"] > BAND_WARN:
        warnings.append(f"seam_band: worst adjacent-line ratio {band_after['max']} within {BAND_K} lines of the wrap "
                        f"(rows {band_after['rows']} at pair {band_after['rows_pair']}, cols {band_after['cols']} at pair "
                        f"{band_after['cols_pair']}; interior reference {band_after['rows_interior_ref']}/"
                        f"{band_after['cols_interior_ref']}) - residual edge band from the raw")

    p2, q2 = slopes(v)
    info["relief_ncc"] = round(relief_ncc(p2, q2, luma), 4)
    if info["relief_ncc"] < 0:
        warnings.append(f"possible inverted relief (band-passed NCC with albedo luma {info['relief_ncc']}); not flipped")
    info["tilt"] = tilt_stats(v)
    if info["tilt"]["near_flat_fraction"] > 0.5:
        warnings.append("more than half of the surface is near-flat")
    info["delivered_vector_length"] = length_stats(decode_rgb(out))
    fp, fq = slopes(decode_rgb(out))
    info["mean_slope_final"] = {"mean_p": round(float(fp.mean()), 4), "mean_q": round(float(fq.mean()), 4),
                                "tilt_deg": round(float(np.degrees(np.arctan(np.hypot(fp.mean(), fq.mean())))), 2)}
    info["steps"], info["warnings"] = steps, warnings
    return out, info


