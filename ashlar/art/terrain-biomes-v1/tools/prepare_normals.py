def short_metrics(m: dict | None) -> list[str]:
    """Compact one-line facts shared by sheets and gallery."""
    if not m:
        return []
    c, r, s = m["convention"], m["registration"], m["seam"]
    state = "applied" if r["applied"] else ("uncertain, not applied" if r["uncertain"] else "not applied")
    shift = f'shift {r["shift_sy"]:+.2f},{r["shift_sx"]:+.2f} px {state} NCC {r["ncc_before"]:.2f}->{r["ncc_after"]:.2f}'
    flags = (" " + ",".join(f.replace("convention_", "") for f in c["flags"])) if c["flags"] else ""
    return [f'{c["decision"]} r {c["r_s0"]}/{c["r_s2"]} d {c["d"]:+.2f}{flags}',
            shift,
            f'relief {m["relief_ncc"]:+.2f} tilt {m["tilt"]["mean_deg"]}/{m["tilt"]["p95_deg"]} deg bias {m["mean_slope_removed"]["tilt_deg"]}',
            f'seam L-R/T-B {s["before"]["edge_lr"]}/{s["before"]["edge_tb"]} -> {s["after"]["edge_lr"]}/{s["after"]["edge_tb"]}'
            f' band x{s["band_after"]["max"]}']


